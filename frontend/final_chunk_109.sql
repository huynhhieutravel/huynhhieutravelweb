<h3 class="wp-block-heading">Khám phá nét kiến trúc, tôn giáo Đạo Dừa kỳ lạ</h3>



<p>Đạo Dừa do ông Nguyễn Thành Nam (25/12/1910) sáng lập nên. Ông xuất thân gia đình giàu có và từng du học bên Pháp và trở về nước làm việc. Sau năm 1945 ông lên Châu Đốc quy y cầu đạo. Sau đó ông ngồi thiền, khổ tu và đi khất thực nhiều năm. Năm 1963 ông về Cồn Phụng và xây dựng nên ngôi chùa Nam Quốc Học với chí hướng truyền bá đạo dừa.</p>



<p>Đạo dừa quan trọng việc đối xử đồng nguyên, hòa thuận với nhau dù gốc gác như thế nào đi nữa. Vì vậy, trong đạo thống của Đạo Dừa thừa hòa hợp nhiều yếu tố lại với nhau. Đặc biệt cả trong kinh kệ lẫn tượng thờ đều xen lẫn 2 đạo phái lớn thời bấy giờ là đạo Phật và đạo Thiên Chúa.</p>



