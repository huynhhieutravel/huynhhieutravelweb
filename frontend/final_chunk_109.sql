<p>Ông từng có lúc nuôi chuột và mèo sống chung với nhau cùng 1 lồng. Qua đó ông muốn chứng minh dù là hai người đối nghịch với nhau thì cũng có thể sống chung hòa thuận cùng nhau. Ngoài ra, từng có thời gian ông cho nam và nữ không mặc đồ sống chung trên đảo. Ông muốn chứng minh sự hòa hợp giữa các mâu thuẫn cùng nhau.</p>



<p>Đôi lúc, tín độ của ông lên đến hàng chục nghìn người. Tuy vậy, do trái với nhiều nguyên tắc của chính quyền. Nên vào năm 1990, công an địa phương đã cấm đoán và đến nơi ông tu đạo cưỡng chế dẹp bỏ. Tuy vậy, lúc thi hành nhiệm vụ đã có sự cố xảy ra, ông bị té từ trên lầu cao. Sau đó, tuy được lập tức đưa đến bệnh viện nhưng không cứu chữa được. Ông Đạo Dừa từ trần, hưởng thọ 81 tuổi (1910 &#8211; 1990).</p>



