<p>Năm 1980, nhà cổ Bình Thủy được ông Dương Văn Ngôn mang về trang trí rất nhiều chậu hoa Lan. Thú chơi lan và sự giao lưu rộng rãi của ông góp phần tạo nên biệt hiệu &#8220;Vườn lan Bình Thủy&#8221; cho ngôi nhà lúc bấy giờ.<br></p>



<h2 class="wp-block-heading">Kiến trúc nhà cổ Bình Thủy</h2>



<p>Kiến trúc nhà cổ Bình Thủy mang đậm dấu ấn Đông Tây. Đây là ngôi nhà cổ phá vỡ quy tắc 3 gian truyền thống trước đây ở miền Tây. Với thiết kế chia thành 5 gian nhà. Diện tích ngôi nhà 6000 mét vuông.</p>



<figure class="wp-block-image"><img loading="lazy" decoding="async" width="1024" height="682" src="https://media.huynhhieutravel.com/nhà-cổ-bình-thủy-cần-thơ-1024x682.jpg" alt="Kiến trúc cổ kính của nhà cổ" class="wp-image-3608" srcset="https://media.huynhhieutravel.com/nhà-cổ-bình-thủy-cần-thơ.jpg 1024w, https://media.huynhhieutravel.com/nhà-cổ-bình-thủy-cần-thơ-768x512.jpg 768w" sizes="(max-width: 1024px) 100vw, 1024px" /><figcaption>Kiến trúc cổ kính của nhà cổ</figcaption></figure>



<p>Đặc biệt vào năm 1911, ông Dương Chấn Kỷ là gia chủ lúc bấy giờ của nhà họ Dương du học ở Pháp về. Ông là người đam mê kiến trúc nên đã đưa ra dự án tu bổ lại ngôi nhà của dòng họ Dương. Kiến trúc được phối hợp 2 nền văn hóa Đông Tây với những thiết kế đặc trưng đậm nét.</p>



<p>Đầu tiên là hàng rào cổng được thiết kế với hàng rào sắt chắn ngang với các cột bê tông làm trụ chính. Nếu bạn không biết rõ lịch sử thì cứ tưởng nó là hàng rào của một ngôi nhà hiện đại nào đó.</p>



<p>Vào bên trong bạn sẽ bắt gặp một cổng tam quan theo lối kiến trúc người Hoa. Cổng tam quan chếch về hướng bên phải từ ngoài nhìn vào. Cổng tam quan này có 4 cột trụ lớn với 2 trụ xi măng và 2 trụ làm bằng gỗ.</p>



<figure class="wp-block-image"><img loading="lazy" decoding="async" width="1024" height="682" src="https://media.huynhhieutravel.com/nhà-cổ-cần-thơ-1024x682.jpg" alt="Một số nội thất xưa và hình ảnh lưu niệm của bộ phim L''amant" class="wp-image-3609" srcset="https://media.huynhhieutravel.com/nhà-cổ-cần-thơ.jpg 1024w, https://media.huynhhieutravel.com/nhà-cổ-cần-thơ-768x512.jpg 768w" sizes="(max-width: 1024px) 100vw, 1024px" /><figcaption>Một số nội thất xưa và hình ảnh lưu niệm của bộ phim L&#8217;amant</figcaption></figure>



<p>Hệ thống xà của cổng được làm bằng gỗ và mái được lợp bằng ngói men xanh. Bên trên trang trí nhiều hình thù sống động với kỳ lân, cá vàng, hoa lá. Ở đó còn có hai bảng hiệu lớn với một bảng hoa là &#8220;Phước An Hiệu&#8221; và một bảng tiếng Việt là &#8220;Phủ thờ họ Dương&#8221;.</p>



<p>Ngoài sân trước nhà là những hàng gạch tàu được lót khoảng 150 năm về trước nhưng vẫn còn mới tinh tươm. Xung quanh sân vườn là những loài hoa kiểng quý: tùng, dương xỉ, cao, phát tài, sứ,&#8230; Đặc biệt, nơi đây còn có nhiều chậu hoa lan và bonsai quý hiếm. </p>



<p>Những loài hoa kiểng này vừa mang lại không khí sinh động cho khuôn viên nhà. Nó lại vừa mang ý nghĩa phong thủy. Ngoài ra, nó còn tác dụng che chắn tầm nhìn khách đi qua ngôi nhà. Giúp ngôi nhà tránh được cái nhìn soi mói của người lạ.</p>



<figure class="wp-block-image"><img loading="lazy" decoding="async" width="1024" height="682" src="https://media.huynhhieutravel.com/nhà-cổ-bình-thủy-ở-cần-thơ-1024x682.jpg" alt="Cánh cửa xanh của ngôi nhà lên hình rất đẹp" class="wp-image-3610" srcset="https://media.huynhhieutravel.com/nhà-cổ-bình-thủy-ở-cần-thơ.jpg 1024w, https://media.huynhhieutravel.com/nhà-cổ-bình-thủy-ở-cần-thơ-768x512.jpg 768w" sizes="(max-width: 1024px) 100vw, 1024px" /><figcaption>Cánh cửa xanh của ngôi nhà lên hình rất đẹp</figcaption></figure>



<p>Góc sân bên trái từ ngoài nhìn vào là một miếu nhỏ thờ thổ thần. Thêm vào đó là bảy bộ ghế ngồi bằng đá.</p>



<p>Bạn phải bước lên cầu thang cao gần 1m để lên gian nhà chính. Có lẽ vì miền Tây là xứ sở hay ngập nước nên ngôi nhà chủ định xây cao hơn để phòng tránh việc này. Đặc biệt, khi xây gian nhà chính ấy, chủ nhân đã dựa theo kinh nghiệm dân gian. Ngôi nhà lót một lớp muối hột khoảng 10cm dưới nền gạch bông.</p>



<p>Thu pháp lót muối dưới gạch bông vừa xua đuổi côn trùng, mang sự thông thoáng ngôi nhà vừa tránh những tà vật xâm hại theo phong thủy. Xung quanh nhà đều là tường gạch, chỉ có những phú hộ giàu có mới xây nhà bằng tường những năm 1900 bấy giờ.</p>



<p>Mái được lợp tổng cộng bởi 3 lớp. Hai lớp dưới được lợp mỏng hình lồng máng để nhìn lên có sự thông thoáng. Cửa gỗ được thiết kế theo phong cách Art – Nouveau của châu Âu. Khi bước vào ngôi nhà, nếu trời nóng bạn sẽ có cảm giác thông thoáng. Nếu trời lạnh bạn sẽ có cảm giác ấm cúng hơn.</p>



<figure class="wp-block-image"><img loading="lazy" decoding="async" width="1024" height="682" src="https://media.huynhhieutravel.com/nhà-cổ-vườn-lan-bình-thủy-1024x682.jpg" alt="Nhà cổ vườn lan Bình Thủy" class="wp-image-3611" srcset="https://media.huynhhieutravel.com/nhà-cổ-vườn-lan-bình-thủy.jpg 1024w, https://media.huynhhieutravel.com/nhà-cổ-vườn-lan-bình-thủy-768x512.jpg 768w" sizes="(max-width: 1024px) 100vw, 1024px" /><figcaption>Nhà cổ vườn lan Bình Thủy</figcaption></figure>



<p>Trong gian nhà chính có ba bộ bàn ghế với chức năng khác nhau. Một bộ dành tiếp khách, một bộ giành cho cả gia đình ăn cơm cùng nhau và một bộ để gia đình ngồi trò chuyện. Toàn bộ căn nhà được nâng bằng 24 cây xà bằng gỗ căm xe.</p>



<p>Bên phải gian nhà từ ngoài nhìn vào là 2 bộ bình bông lớn cỡ người thật. Trên tường là những tấm bằng khen được treo đầy. Bên trái gian nhà là những tấm ảnh lưu niệm từ các bộ phim, vài dòng ký gửi đạo diễn và một vài tờ báo cắt ra nói về nhà cổ Bình Thủy.</p>



<p>Chính giữa nhà là một gian thờ lớn theo đúng kiểu người <strong>Nam bộ xưa</strong>. Bộ bài vị, lư hương, đèn đầy đủ. Đặc biệt, những kiến trúc chạm trổ của ngôi nhà đều rất tinh tế.</p>



<p>Nếu nhìn kỹ bạn sẽ nhận ra ngôi nhà điêu khắc khá nhiều động vật mang lại hưng thịnh theo quan điểm người xưa. Từ những thực vật như mai, sen, cúc, trúc, lan đến hình tượng động vật như lộc, dơi, chim, công, tôm, cua, rồng, phượng,&#8230;</p>



<figure class="wp-block-image"><img loading="lazy" decoding="async" width="1024" height="682" src="https://media.huynhhieutravel.com/đi-nhà-cổ-bình-thủy-du-lịch-nào-1024x682.jpg" alt="Đi nhà cổ Bình Thủy du lịch nào!" class="wp-image-3612" srcset="https://media.huynhhieutravel.com/đi-nhà-cổ-bình-thủy-du-lịch-nào.jpg 1024w, https://media.huynhhieutravel.com/đi-nhà-cổ-bình-thủy-du-lịch-nào-768x512.jpg 768w" sizes="(max-width: 1024px) 100vw, 1024px" /><figcaption>Đi nhà cổ Bình Thủy du lịch nào!</figcaption></figure>



<p>Ngôi nhà cũng lưu giữ khá nhiều vật cổ với các bộ bàn ghế làm bằng đá cẩm thạch có xuất xứ từ Trung Quốc. Ngoài ra còn có bộ salon từ Pháp mang sang và cặp đèn treo từ thế kỷ 19.</p>



<p>Vào năm 2009, nhà cổ Bình Thủy đã được bộ Văn hóa &#8211; Thể thao và Du lịch công nhận Di tích kiến trúc nghệ thuật cấp quốc gia.</p>



<p>Hiện nhà cổ Bình Thủy vẫn do con cháu dòng họ Dương nằm giữ và lưu truyền. Nó cũng là ngôi nhà duy nhất còn thuộc sở hữu tư nhân trong 3 ngôi nhà cổ lớn và nổi tiếng ở miền Tây. Bên cạnh nó là nhà cổ <a rel="noreferrer noopener" aria-label="Công tử Bạc Liêu (mở trong tab mới)" href="https://huynhhieutravel.com/cong-tu-bac-lieu" target="_blank">Công tử Bạc Liêu</a> ở Bạc Liêu, nhà cổ Huỳnh Thủy Lê ở Đồng Tháp.</p>



