<h3 class="wp-block-heading">Lá bùa Lỗ Ban ếm phong thủy ngôi nhà</h3>



<p>Người ta đồn rằng, trên đòn dong hay đâu đó ở ngôi nhà cổ Bình Thủy này có ếm một lá bùa Lỗ Ban phong thủy. Nhờ vậy mà dòng họ Dương mới phất lên làm giàu nhanh chóng như vậy.</p>



<p>Tương truyền, lúc ấy trong vùng có ông Ba Nghĩa theo học nghề phong thủy Lỗ Ban (Người ta còn gọi ông Lỗ Ban). Lúc nào ra đường ông cũng quấn chiếc khăn điều màu đỏ chót lên đầu. Bên cạnh ông lúc nào cũng có chiếc riều và một cái nẻ mực (Đây là loại dây nhợ có tẩm mực tàu, dùng để tạo đường thẳng chặt gỗ hoặc đo đạc gỗ). </p>



<p>Bất kỳ một nhà phú hộ nào khi xây nhà đều phải nhờ ông &#8220;Lỗ Ban&#8221; đến xây cho nhà đẹp. Nhà họ Dương khi xây nhà cũng như vậy, phải mời thầy ấy lại thì nhà mới tốt. Nhưng nhà họ Dương lại đưa thêm một điều kiện khác.</p>



<p>&#8220;Thầy xây nhà tôi đẹp rực rỡ hay lung linh hơn nhà khác thì cũng thường quá. Tôi muốn là thầy xây nhà sao cho nhà tôi làm ăn khấm khá và giàu lên hơn như thế này mới được.&#8221;</p>



<p>Lúc ấy ông thầy Lỗ Ban đã có ý từ chối: &#8220;Khó nỗi cái nghề của tôi muốn gia chủ giàu thì mình phải cắn trả nghèo cùn nghèo mạt thì mới được.&#8221;</p>



<p>Ông Dương Chấn Kỷ khi nghe xong phất tay bảo: &#8220;Đừng lo, thầy cứ làm cho tôi. Mỗi tháng tôi sẽ chu cấp cho thầy 1 đấu gạo và 3 cắc bạc đến mãn đời&#8221;. Lúc ấy ông Ba Nghĩa Lỗ Ban trầm tư rồi mỉm cười đồng ý.</p>



<p><em><a href="https://dantri.com.vn/xem-an-choi/loi-nguyen-lo-ban-giai-ma-nhung-cam-bay-ky-di-nhat-cua-trung-hoa-co-dai-1366783452.htm" target="_blank" rel="noreferrer noopener nofollow" aria-label="Lỗ Ban (mở trong tab mới)">Lỗ Ban</a> trước đây là một bậc thầy về nghề mộc ở Trung Quốc. Ông có tay nghề khéo léo cùng với khả năng phong thủy tuyệt vời. Những người làm nghề Lỗ Ban trước đây ở Việt Nam luôn là những bậc cao tay ấn về phong thủy. Nhưng tương truyền làm nghề Lỗ Ban cũng chịu cắn trả cực kỳ thảm khốc.</em></p>



<p><em>Bạn phải nuôi một con ngãi, chuyên phục vụ cho mình. Quy luật của nó là cân bằng. Nếu gia hại người khác thì bạn sẽ tạo thói quen cho nó. Từ đó nó sẽ cắn trả lại người nuôi liên tục. Nếu người Lỗ Ban chết đi, nó sẽ lưu truyền theo huyết mạch. Hoặc nếu muốn làm giàu người khác, người Lỗ Ban cũng chịu phản ngược lại. </em></p>



<p>Mình chỉ ghi lại một góc cạnh của nghề Lỗ Ban cho bạn biết. Nó có thể chưa đủ hoặc đôi chút sai lệch vì mình chỉ nghe người khác kể lại. Nghề Lỗ Ban hiện giờ vẫn còn ở Việt Nam nhưng khá hiếm vì tỷ lệ thất truyền khá cao.</p>



<h3 class="wp-block-heading">Câu chuyện về bảy bộ ghế đá sau vườn</h3>



<p>Năm 1945, thực dân Pháp xâm lược nước ta <a rel="noreferrer noopener nofollow" aria-label="lần 2 (mở trong tab mới)" href="https://alphahistory.com/vietnamwar/vietnam-war-timeline-1946-1954/" target="_blank">lần 2</a>. Nhà nước lâm thời lúc bấy giờ phát động toàn dân kháng chiến. Vào tháng 12 năm 1945, quân đội ta ở Cần Thơ đụng độ quân Pháp. Lúc ấy tiếng súng nổ vang cả trời, thỉnh thoảng những tiếng lựu đạn lại nổ ầm ầm. tô điểm thêm sự ác liệt của cuộc đấu súng đôi bên. Chúng ta phục kích tiêu diệt nhiều sĩ quan Pháp nhưng cũng hy sinh hết 7 người lính anh dũng.</p>



<p>Lúc ấy, để tưởng nhớ chiến công và sự hy sinh anh dũng của 7 người lính. Ông Dương Văn Ngôn đã cho xây dựng 7 bộ ghế đá. Khi xây xong, quân Pháp đã tra hỏi nhưng ông chỉ bảo đây là chỉ bảy vị thất hiền của Trung Quốc xưa. Nên quân Pháp cũng không thể làm gì được ông.</p>



<h3 class="wp-block-heading">Cây xương rồng ở nhà cổ Bình Thủy</h3>



<p>Cây xương rồng này được nhập từ Mexico về. Nó được đặt ở trước một quán cafe trong khuôn viên của nhà cổ Bình Thủy. Cây xương rồng cao hơn 10m với độ tuổi xấp sỉ 40 năm. Đây là loại hiếm và khó tìm thấy được ở Việt Nam bây giờ.</p>



<h3 class="wp-block-heading">Phim trường của nhiều bộ phim nổi tiếng</h3>



