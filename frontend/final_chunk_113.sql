<h2 class="wp-block-heading">Truyền kỳ về nhà cổ Bình Thủy</h2>



<p>Nhà cổ Bình Thủy là một kiến trúc mang đậm nét văn hóa nhà cổ của các phú hào ngày xưa ở miền Tây. Bên cạnh sự nổi tiếng từng là phim trường của nhiều bộ phim thì những <strong>truyền kỳ</strong> ở đây cũng thu hút nhiều người quan tâm.</p>



