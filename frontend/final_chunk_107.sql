<h3 class="wp-block-heading">Từ thầy ký Trạch trở thành một ông hội đồng Trạch giàu có</h3>



<figure class="wp-block-image"><img loading="lazy" decoding="async" width="1024" height="853" src="https://media.huynhhieutravel.com/tách-trà-cổ-từ-thời-nhà-thanh-của-công-tử-bạc-liêu-1024x853.jpg" alt="Tách trà cổ" class="wp-image-3513"/><figcaption>Tách trà cổ</figcaption></figure>



<p>Lúc bấy giờ, nhờ làm việc ủy ban tỉnh Bạc Liêu nên ông thường hay tiếp xúc cùng những phú hộ giàu có. Ông vừa thông minh, lại siêng năng, phóng khoáng giúp đỡ nhiều phú hộ về đóng thuế tô đất. Ông bắt đầu được ông bá hộ Phan Văn Bì &#8211; cũng là bá hộ giàu có bấy giờ, để ý đến.</p>



<p>Ông Bì tạo điều kiện cho thầy ký Trạch làm quen con gái của mình. Khi thấy cả hai hợp ý, ông đã gả con gái cho ông Trạch và chia một số đất đai, gia sản để ông quản lý. Ông Trạch nghỉ việc thư kỷ ở ủy ban về quản lý gia sản được giao cho.</p>



<figure class="wp-block-image"><img loading="lazy" decoding="async" width="1024" height="853" src="https://media.huynhhieutravel.com/nhà-cổ-công-tử-bạc-liêu-1024x853.jpg" alt="Nhà cổ Công tử Bạc Liêu" class="wp-image-3506"/><figcaption>Nhà cổ Công tử Bạc Liêu</figcaption></figure>



<p>Với đầu óc của một người có học và thông minh, ông Trạch nhanh chóng vươn lên, mở rộng gia sản của mình hơn nữa. Không những giỏi việc quản lý đất đai, ông Trạch còn mở rộng kinh doanh theo nhiều hướng mới. Ông còn xin được độc quyền cả việc cầm đồ. Lúc bấy giờ, thuật ngữ cầm đồ khá mới mẻ.</p>



<p>Sau này, ngay cả chính những người anh em rể của ông Trạch vì ham mê cờ bạc. Họ cũng mất dần gia sản vào tay ông. Ông bá hộ Bì trước khi chết cũng ngậm ngùi tự an ủi rằng: ít ra, gia sản của mình cũng không rơi hết vào tay người ngoài mà là vào tay con rể và con gái.</p>



<p>Theo thống kê, ngoài những gia sản khác, ông bá hộ Trạch lúc bấy giờ sở hữu 74 sở điền lớn, 110.000 ha ruộng lúa và 100.000 ha ruộng muối.</p>



<figure class="wp-block-image"><img loading="lazy" decoding="async" width="1024" height="853" src="https://media.huynhhieutravel.com/đồ-dùng-tinh-xảo-nhà-công-tử-bạc-liêu-1024x853.jpg" alt="Đồ dùng tinh xảo" class="wp-image-3495"/><figcaption>Đồ dùng tinh xảo</figcaption></figure>



<h3 class="wp-block-heading">Cậu ba Huy đi du học và sự kỳ vọng lớn lao</h3>



<p>Ông hội đồng Trạch là người có ăn học cộng với sự từng trải nhiều biến cố. Ông hiểu thế nào nếu con của mình không quản lý tài sản của mình tốt. Ông nhận thấy dù mình giàu như ba vợ thì cũng có ngày gia sản có thể mất hết do con cái.</p>



<p>Khi ấy, ông kỳ vọng vào con trai thứ ba của mình là cậu Trần Trinh Huy. Một chàng trai trẻ thông minh, học hành giỏi giang. Ông đưa con mình sang Pháp du học. Mong rằng con mình sẽ học rộng thành tài, về quản lý gia sản của mình.</p>



<figure class="wp-block-image"><img loading="lazy" decoding="async" width="1024" height="1024" src="https://media.huynhhieutravel.com/bình-sứ-cổ-nhà-công-tử-bạc-liêu-1024x1024.jpg" alt="Bình sứ cổ nhà Công tử Bạc Liêu" class="wp-image-3487" srcset="https://media.huynhhieutravel.com/bình-sứ-cổ-nhà-công-tử-bạc-liêu-1024x1024.jpg 1024w, https://media.huynhhieutravel.com/bình-sứ-cổ-nhà-công-tử-bạc-liêu-150x150.jpg 150w" sizes="(max-width: 1024px) 100vw, 1024px" /><figcaption>Bình sứ cổ</figcaption></figure>



<p>Tuy vậy, khi sang Pháp du học, cậu ba Huy lại giỏi nhiều thứ khác hơn là chuyện đi học. Cậu học đủ các bằng thời thượng lúc bấy giờ: bằng nhảy đầm, bằng láy xe hơi, bằng láy xe máy, bằng láy máy bay,&#8230; Cậu ba Huy sang Pháp chỉ thường đi nông trường học hỏi kỹ thuật, cách quản lý của họ. Ngoài ra, thời gian còn lại cậu chỉ lo vào việc vui chơi. Cậu còn cưới một người vợ Tây bên Pháp và có một người con.</p>



<figure class="wp-block-image"><img loading="lazy" decoding="async" width="1024" height="853" src="https://media.huynhhieutravel.com/giường-công-tử-bạc-liêu-1024x853.jpg" alt="Giường Công tử Bạc Liêu" class="wp-image-3496"/><figcaption>Giường Công tử Bạc Liêu</figcaption></figure>



<h3 class="wp-block-heading">Cậu ba Huy về nước và truyền kỳ công tử Bạc Liêu bắt đầu</h3>



<p>Cuối năm 1926, chàng trai 26 tuổi Trần Trinh Huy kết thúc chuyến du học về nước với bao điều thú vị sắp sửa mở ra. Nghe tin con mình về nước, ông hội đồng Trạch vui mừng thân chinh cùng vợ mình lên Sài Gòn đón cậu ba về.</p>



<p>Tương truyền, khi lên Sài Gòn, ông hội đồng Trạch cầm túi xách nhà quê, mặc áo bà bà và mang đôi dép lào vào tiệm bán xe hơi sang trọng nhất Sài thành lúc bấy giờ. Ban đầu, người nhân viên ở đây cười cái chất nhà quê lôi thôi của ông già xách giỏ xách lựa xe hơi này.</p>



<figure class="wp-block-image"><img loading="lazy" decoding="async" width="1024" height="853" src="https://media.huynhhieutravel.com/xe-cổ-công-tử-bạc-liêu-1024x853.jpg" alt="Xe cổ của Công tử Bạc Liêu" class="wp-image-3514"/><figcaption>Xe cổ của Công tử Bạc Liêu</figcaption></figure>



<p>Nhưng khi ông hội đồng Trạch bảo lấy xe hơi đời mới nhất, mắc nhất là chiếc Peugeot hiện đại lúc bấy giờ ra. Ông hội đồng Trạch cầm giỏ xách mở ra những cọc tiền mặt làm cho người nhân viên bán xe phải trố mắt nhìn.</p>



<p>Cậu ba Huy khi gặp cha mình đã lập tức trổ tài lái xe của mình. Ông láy xe với vận tốc gần 100km/h từ Sài Gòn về Bạc Liêu. Ông hội đồng Trạch lúc đó mở tiệc lớn chiêu đãi tất cả mọi người. Lúc ấy, hàng nghìn vị khách là quan lớn, bá hộ giàu có lúc tỉnh Nam kỳ đều đến dự tiệc chúc mừng.</p>



<figure class="wp-block-image"><img loading="lazy" decoding="async" width="1024" height="880" src="https://media.huynhhieutravel.com/hành-lang-nhà-công-tử-bạc-liêu-1024x880.jpg" alt="Hành lang nhà Công tử Bạc Liêu" class="wp-image-3497"/><figcaption>Hành lang nhà Công tử Bạc Liêu</figcaption></figure>



<h3 class="wp-block-heading">Tài trí của Công tử Bạc Liêu</h3>



<p>Ông tuy nổi tiếng về sự ăn chơi của mình, nhưng ông cũng rất tài tình và học rộng biết nhiều. Ông hội đồng Trạch là người có ăn học, lại làm ăn lâu năm. Ông không đơn giản giao toàn bộ tài sản của mình cho đứa ăn chơi phá của quản lý.</p>



<figure class="wp-block-image"><img loading="lazy" decoding="async" width="1024" height="853" src="https://media.huynhhieutravel.com/bộ-bàn-ghế-của-công-tử-bạc-liêu-1024x853.jpg" alt="Bộ bàn ghế" class="wp-image-3488"/><figcaption>Bộ bàn ghế</figcaption></figure>



<h4 class="wp-block-heading">Quản lý tài sản như người Tây</h4>



<p>Khi nghe cha mình muốn giao toàn bộ tài sản để ông quản lý. Cậu ba Huy đã giao kèo với ba mình rằng mọi tài sản phải được ông toàn quyền quản lý. Ông hội đồng Trạch không được phép xen vào và phải tuân thủ quy trình quản lý. Mọi thu chi đều phải có sổ sách rõ ràng. Ngay cả khi lấy tiền, ông hội đồng Trạch cũng phải xin phép cậu ba Huy.</p>



<figure class="wp-block-image"><img loading="lazy" decoding="async" width="1024" height="853" src="https://media.huynhhieutravel.com/khách-tham-quan-nhà-công-tử-bạc-liêu-1024x853.jpg" alt="Khách tham quan nhà Công tử Bạc Liêu" class="wp-image-3499"/><figcaption>Khách tham quan nhà Công tử Bạc Liêu</figcaption></figure>



<h4 class="wp-block-heading">Mở ngân hàng đầu tiên Việt Nam</h4>



<p>Cậu ba Huy cũng là người đề xuất cha mình mở ngân hàng đầu tiên ở Việt Nam. Ngân hàng được mở ra, nhiều bá hộ giàu có đều góp vốn và gửi tiền vào đó.</p>



<figure class="wp-block-image"><img loading="lazy" decoding="async" width="1024" height="853" src="https://media.huynhhieutravel.com/bộ-bàn-ghế-nhà-công-tử-bạc-liêu-1024x853.jpg" alt="Bộ bàn ghế nhà Công tử Bạc Liêu" class="wp-image-3489"/><figcaption>Bộ bàn ghế nhà Công tử Bạc Liêu</figcaption></figure>



<h4 class="wp-block-heading">Thuê chuyên gia Pháp quản lý tài sản cho mình</h4>



<p>Ông biết rằng với gia sản đồ sộ của gia đình, ông không đủ khả năng và trình độ quản lý toàn bộ chúng. Ông cũng sợ mất thời gian vào công việc và bỏ lỡ việc ăn chơi của mình. Sẽ rất có tội nếu có tiền mà bạn không biết sử dụng chúng mà bị chúng chi phối. Vì thế ông cho thuê một quản lý có tiếng người Pháp là ông Henry. Ông Henry ban đầu từ chối nhưng với số hoa hồng 10% lợi nhuận hàng năm hấp dẫn ông đã nhận lời.</p>



<figure class="wp-block-image"><img loading="lazy" decoding="async" width="1024" height="853" src="https://media.huynhhieutravel.com/không-gian-nhà-công-tử-bạc-liêu-1024x853.jpg" alt="Không gian nhà Công tử Bạc Liêu" class="wp-image-3500"/><figcaption>Không gian nhà Công tử Bạc Liêu</figcaption></figure>



<h4 class="wp-block-heading">Mở đầu những thứ mới mẻ ở Việt Nam</h4>



<p>Khi du học ở nước ngoài về, tư tưởng mới mẻ trong đầu Công tử Bạc Liêu luôn rất tiến bộ. Ông là người rất coi trọng việc bình đẳng nam nữ. Ông muốn con gái cũng phải có ăn học, biết ra ngoài xã hội làm việc. Ông là người đầu tiên tổ chức các cuộc thi hoa hậu miệt vườn ở miền Nam lúc bấy giờ. Tuy rằng, lúc đó ông cũng chọn ra các cô nhân tình của mình từ những thí sinh đi thi.</p>



<figure class="wp-block-image"><img loading="lazy" decoding="async" width="1024" height="853" src="https://media.huynhhieutravel.com/bộ-đèn-cổ-nhà-công-tử-bạc-liêu-1024x853.jpg" alt="Bộ đèn cổ nhà Công tử Bạc Liêu" class="wp-image-3490"/><figcaption>Bộ đèn cổ nhà Công tử Bạc Liêu</figcaption></figure>



<p>Ông cũng là người tư vấn các quan trưởng mở các hội chợ ở các làng quê Việt Nam. Những buổi hội chợ là những ngày buôn bán tấp nập hàng hóa. Những thương gia, nông dân cùng nhau trẫy hội, mua sắm, vui chơi.</p>



<h4 class="wp-block-heading">Người lấy gốc là nông dân</h4>



<p>Một lần trong bữa ăn, ông hỏi cha mình rằng: Cha có biết nhà mình giàu là do đâu không? Ông hội đồng Trạch bất ngờ và trả lời rằng: Là do mình làm ăn tích cóp, mở rộng mua bán, ruộng lúa bạt ngàn. ông mới mỉm cười trả lời: Cha sai rồi, nhà mình giàu là do tá điền. Chính họ là người trông coi ruộng đất, nộp tô thuế hàng năm cho chúng ta.</p>



<p>Ông luôn coi trọng nhưng người nông dân, tá điền làm việc cho nhà mình. Hàng năm vào dịp lễ Tết, ông thường tổ chức phát tiền, lễ hội. Ông cũng thường làm lễ xóa nợ cho người tá điền nợ tiền mình.</p>



<figure class="wp-block-image"><img loading="lazy" decoding="async" width="1024" height="863" src="https://media.huynhhieutravel.com/bộ-tủ-bàn-ghế-nhà-công-tử-bạc-liêu-1024x863.jpg" alt="Bộ tủ bàn ghế" class="wp-image-3491"/><figcaption>Bộ tủ bàn ghế</figcaption></figure>



<h4 class="wp-block-heading">Mua máy bay để làm ruộng</h4>



<p>Công tử Bạc Liêu từng sở hữu chiếc máy bay tư nhân đầu tiên Việt Nam với nhiều truyền kỳ. Nhưng chuyện kể lại ông mua máy bay là để&#8230; làm ruộng. Trước đây, nạn châu chấu ăn ruộng lúa thường hoành hành. Có những lúc, châu chấu bay đen nghẹt cả bầu trời. Người dân không thể nào ứng cứu kịp thời những đồng lúa bị nạn châu chấu lướt qua.</p>



<p>Ruộng lúa của ông lúc bấy giờ lại bạt ngàn mênh mông. Để ứng cứu và chăm coi ruộng lúa tốt hơn, vừa thể hiện đẳng cấp ăn chơi của mình với bằng láy máy bay học bên Pháp. Với đầy đủ các lý do, ông đã đặt mua một chiếc máy bay về để làm ruộng. Chiếc máy bay lúc đó tương truyền được mua với giá 100kg vàng.</p>



<figure class="wp-block-image"><img loading="lazy" decoding="async" width="1024" height="916" src="https://media.huynhhieutravel.com/căn-phòng-nhà-công-tử-bạc-liêu-1024x916.jpg" alt="Căn phòng dần hư hao theo thời gian" class="wp-image-3492"/><figcaption>Căn phòng dần hư hao theo thời gian</figcaption></figure>



<h3 class="wp-block-heading">Những người vợ của Công tử Bạc Liêu</h3>



<p>Ông có 3 người vợ chính thức và tương truyền có đến hàng trăm người tình bên ngoài. Người vợ đầu của ông là bà Ngô Thị Đen &#8211; người con gái đẹp nhất xứ Bạc Liêu lúc bấy giờ. Người vợ hai là con một phú hộ giàu có ở Mỹ Tho là bà Nguyễn Thị Hai. Người vợ thứ ba là con thứ ba của người sửa xe đạp cũng có cái tên là Ba.</p>



<p>Đặc biệt, khi du học ở bên Pháp, ông còn có một người vợ không chính thức là người Tây. Cô Tây ấy tên là Marie, một nhân viên thu ngân ở Pháp.&nbsp; Hai người ở với nhau và có một người con trai tên là Richard, sau này trở thành phi công. Nhưng do khác biệt văn hóa, khi về nước ông để hai mẹ con ở lại Paris và về nước.</p>



<figure class="wp-block-image"><img loading="lazy" decoding="async" width="1024" height="853" src="https://media.huynhhieutravel.com/chiếc-ghế-được-chạm-trổ-xà-cừ-tỉ-mỉ-1024x853.jpg" alt="Chiếc ghế được chạm trổ xà cừ tỉ mỉ" class="wp-image-3493"/><figcaption>Chiếc ghế được chạm trổ xà cừ tỉ mỉ</figcaption></figure>



<p>Ngoài ra, ông còn có hàng chục người con bên ngoài khác nhau. Tuy dòng họ Trần Trinh không chấp nhận những người vợ ngoài của Công tử Bạc Liêu. Nhưng những người con đều được liệt vào gia phả và phân chia tài sản.</p>



<h3 class="wp-block-heading">Sự khánh kiệt của Công tử Bạc Liêu &#8211; Sự tàn lụi gia tộc Trần Trinh</h3>



<p>Giàu có là thế, ăn chơi khét tiếng là thế nhưng ông về già cũng khó khăn và gia sản gia tộc Trần Trinh cũng bị khánh kiệt dần. Người ta đồn thổi nói rằng Công tử Bạc Liêu do ăn chơi mà trở nên phá sản.</p>



