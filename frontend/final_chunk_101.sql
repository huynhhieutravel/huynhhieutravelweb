<h3 class="wp-block-heading">10 ngày lễ hội Phủ Giầy</h3>



<p>Lễ hội kéo dài trong 10 ngày từ mùng 1/3 đến 10/3 âm lịch tại Phủ Giầy.</p>



<ul class="wp-block-list"><li>Mùng 1: Lễ nhập hội. Họ Trần Lê (Dòng họ của Mẫu Liễu) vào làm lễ tại Phủ Chính rồi sang nơi thờ họ Lê ở phủ Nội và phủ Ngoại. Phủ Vân Cát cũng làm lễ nhập hội và làng lo việc tế.</li><li>Mùng 2: Làng cử hành lễ vào buổi tối và kèm theo lễ rước nước với đuốc thắp sáng. Nước được lấy vào chum (chĩnh) về tắm tượng Thánh Mẫu (Hay còn gọi là lễ Mộc Dục).</li><li>Mùng 3: Ngày lễ chính giỗ Mẫu Liễu Hạnh và được tổ chức lễ ở phủ Tiên Hương. Lễ vật bao gồm: nhang đèn, hoa quả, 100 bánh giầy lớn, một con lợn sống. Trong ngày này phủ Vân Cát cũng làm lễ với lễ cúng: một trâu thui, một bò thui, một lợn luộc (Tam sinh), hoa quả và một trăm cặp bánh giày.</li><li>Mùng 4 và 5: Lễ tế tiếp, các chức sắc trong làng sẽ tế theo thứ tự định trước.</li><li>Mùng 6: Rước Thánh Mẫu từ phủ Tiên Hương đến chùa Gôi. Đám rước kéo dài gần 1km với quy mô lớn và trang trọng. Thành phần dự gồm nhà chùa (Hòa thượng), Mẫu Liễu (Đạo Tứ Phủ), các quan chức và các người hành nghề cúng đạo, kèm theo là đội lân sư rồng.</li></ul>



