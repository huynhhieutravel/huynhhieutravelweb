<ul class="wp-block-list"><li>Mùng 7, 8 và 9: Trò chơi Kéo chữ được diễn ra. Đây là nét đặc trưng độc đáo của lễ hội Kẻ Giầy. Mỗi lần xếp chữ cần trên 100 phu cờ ăn mặc đồng phục chỉnh tề. Khăn xếp trên đầu (Chít khăn), áo vàng, thắt lưng xanh, quần trắng, xà cạp đỏ. Mỗi người cầm một cây gậy khoảng 2m. Sẽ có một người điều khiển gọi là tổng cờ. Khi trò chơi bắt đầu, chủ lễ sẽ xin Mẫu ra chữ sau đó tổng cờ ra lệnh phu cờ xếp theo chữ. </li></ul>



