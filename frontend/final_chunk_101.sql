<h2 class="wp-block-heading">Kiến trúc Phủ Giầy</h2>



<p>Phủ Giầy có bộ 3 kiến trúc chính thờ Mẫu Liễu Hạnh: Phủ Tiên Hương (Phủ chính), phủ Vân Cát và Lăng Chúa Liễu.</p>



<h3 class="wp-block-heading">Phủ Tiên Hương</h3>



<p>Phủ Tiên Hương (Phủ chính) là công trình đẹp nhất. Trước phủ là một chiếc giếng tròn với một cột cờ ở giữa. Nó nối với một sân rộng với một hệ thống nghi môn trụ, trên đỉnh là lân và phụng. Kế đến là ba tòa nhà ngang: nhà chiêng, nhà trống và nhà bia. Một hồ bán nguyệt bao quanh với bình phong và hai cầu vượt đều bằng đá. </p>



<p>Điện thờ chính thờ Mẫu Tứ Phủ, Mẫu Thượng Thiên (Trời) ở giữa. Thờ Mẫu Địa (Đất) bên phải. Thờ Mẫu Thoải (Nước) bên trái. Thờ Mẫu Thượng Ngàn (Núi Rừng) ở phía trước.</p>



<h3 class="wp-block-heading">Phủ Vân Cát</h3>



<p>Phía trước phủ Vân Cát là một hồ bán nguyệt. Đi tiếp sẽ gặp ngũ môn. Trung tâm là nơi thờ Chúa Liễu. Khu vực bên trái thờ các tượng Phật và bên phải là đền thờ Lý Nam Đế.</p>



