<p>Kolb cho rằng việc học liên quan đến việc tiếp thu các khái niệm trừu tượng có thể áp dụng linh hoạt trong nhiều tình huống.&nbsp;Theo lý thuyết của Kolb, động lực phát triển các khái niệm mới được cung cấp bởi những trải nghiệm mới.</p>



<blockquote class="wp-block-quote is-layout-flow wp-block-quote-is-layout-flow">
<p>“Học tập là quá trình trong đó kiến thức được tạo ra thông qua việc chuyển đổi kinh nghiệm” (Kolb, 1984, trang 38).</p>
</blockquote>



<h2 class="wp-block-heading">Chu Trình Học Tập Trải Nghiệm</h2>



<p>Lý thuyết về phong cách học tập theo trải nghiệm của Kolb thường được thể hiện bằng một chu trình học tập gồm 4 giai đoạn, trong đó người học “chạm vào tất cả các cơ sở”:</p>



<figure class="wp-block-image size-full" id="attachment_553"><img loading="lazy" decoding="async" width="942" height="942" src="https://media.huynhhieutravel.com/chu-trinh-hoc-tap-trai-nghiem.jpg" alt="Chu trình học tập trải nghiệm Kolb" class="wp-image-12122" srcset="https://media.huynhhieutravel.com/chu-trinh-hoc-tap-trai-nghiem.jpg 942w, https://media.huynhhieutravel.com/chu-trinh-hoc-tap-trai-nghiem-300x300.jpg 300w, https://media.huynhhieutravel.com/chu-trinh-hoc-tap-trai-nghiem-150x150.jpg 150w, https://media.huynhhieutravel.com/chu-trinh-hoc-tap-trai-nghiem-768x768.jpg 768w" sizes="(max-width: 942px) 100vw, 942px" /><figcaption class="wp-element-caption">Chu trình học tập trải nghiệm Kolb</figcaption></figure>



<ol class="wp-block-list">
<li><strong>Trải nghiệm cụ thể</strong> – người học gặp phải một trải nghiệm cụ thể. Đây có thể là một trải nghiệm hoặc tình huống mới hoặc sự diễn giải lại trải nghiệm hiện có dưới ánh sáng của các khái niệm mới.</li>



<li><strong>Quan sát phản ánh trải nghiệm mới</strong> – người học phản ánh về trải nghiệm mới dưới ánh sáng kiến thức hiện có của họ. Điều đặc biệt quan trọng là bất kỳ sự mâu thuẫn nào giữa kinh nghiệm và sự hiểu biết.</li>



<li><strong>Khái niệm hóa trừu tượng</strong> – sự phản ánh làm nảy sinh một ý tưởng mới hoặc sửa đổi một khái niệm trừu tượng hiện có (người đó đã học được từ kinh nghiệm của họ).</li>



<li><strong>Thử nghiệm tích cực</strong> – các khái niệm mới được tạo hoặc sửa đổi sẽ dẫn đến thử nghiệm. Người học áp dụng (các) ý tưởng của mình vào thế giới xung quanh để xem điều gì sẽ xảy ra.</li>
</ol>



<blockquote class="wp-block-quote is-layout-flow wp-block-quote-is-layout-flow">
<p>Học tập hiệu quả được thấy khi một người tiến bộ qua 1 chu kỳ gồm 4 giai đoạn:</p>



<p>(1) có một trải nghiệm cụ thể, sau đó là (2) quan sát và suy ngẫm về trải nghiệm đó dẫn đến (3) hình thành các khái niệm trừu tượng (phân tích) và khái quát hóa (kết luận) mà sau đó (4) được sử dụng để kiểm tra một giả thuyết trong các tình huống trong tương lai, dẫn đến những trải nghiệm mới.</p>
</blockquote>



<figure class="wp-block-image size-full"><img loading="lazy" decoding="async" width="812" height="812" src="https://media.huynhhieutravel.com/chu-trinh-hoc-tap-Kolbs.jpg" alt="" class="wp-image-12121" srcset="https://media.huynhhieutravel.com/chu-trinh-hoc-tap-Kolbs.jpg 812w, https://media.huynhhieutravel.com/chu-trinh-hoc-tap-Kolbs-300x300.jpg 300w, https://media.huynhhieutravel.com/chu-trinh-hoc-tap-Kolbs-150x150.jpg 150w, https://media.huynhhieutravel.com/chu-trinh-hoc-tap-Kolbs-768x768.jpg 768w" sizes="(max-width: 812px) 100vw, 812px" /></figure>



<p>Kolb xem việc học tập như một quá trình tích hợp, trong đó mỗi giai đoạn hỗ trợ lẫn nhau và bổ sung cho giai đoạn tiếp theo. Có thể tham gia vào chu trình ở bất kỳ giai đoạn nào và thực hiện theo trình tự logic của nó.</p>



<p>Tuy nhiên, việc học hiệu quả chỉ xảy ra khi người học có thể thực hiện được cả 4 giai đoạn của mô hình. Do đó, không có giai đoạn nào của chu trình tự nó có hiệu quả như một quá trình học tập.</p>



<p>Quá trình trải qua chu trình dẫn đến việc hình thành các ‘mô hình tinh thần’ ngày càng phức tạp và trừu tượng về bất cứ điều gì người học đang học.</p>



<h2 class="wp-block-heading">Chu Kỳ Suy Ngẫm Của Kolb</h2>



<p>Lý thuyết học tập của Kolb đặt ra 4 phong cách học tập riêng biệt, dựa trên chu trình học tập 4 giai đoạn (xem ở trên).&nbsp;Kolb giải thích rằng những người khác nhau sẽ thích một phong cách học tập khác nhau một cách tự nhiên.</p>



<p>Có nhiều yếu tố khác nhau ảnh hưởng đến phong cách ưa thích của một người.&nbsp;Ví dụ: môi trường xã hội, trải nghiệm giáo dục hoặc cấu trúc nhận thức cơ bản của cá nhân.</p>



<p>Bất kể điều gì ảnh hưởng đến việc lựa chọn phong cách, bản thân sở thích về phong cách học tập thực sự là sản phẩm của 2 cặp biến số hoặc 2 “lựa chọn” riêng biệt mà chúng ta đưa ra, mà Kolb trình bày dưới dạng các đường của một trục, mỗi lựa chọn có các phương thức “xung đột” ở hai đầu.</p>



<p>Một cách trình bày điển hình về 2 phạm vi liên tục của Kolb là trục đông-tây được gọi là Liên tục xử lý (cách chúng ta tiếp cận một nhiệm vụ) và trục bắc-nam được gọi là Liên tục nhận thức (phản ứng cảm xúc của chúng ta hoặc cách chúng ta suy nghĩ hoặc cảm nhận về Nó).</p>



<p>Kolb tin rằng chúng ta không thể thực hiện cả 2 biến số trên một trục cùng một lúc (ví dụ: suy nghĩ và cảm nhận).&nbsp;Phong cách học tập của chúng ta là sản phẩm của 2 quyết định lựa chọn này.</p>



<p>Thường dễ dàng hơn để thấy việc xây dựng các phong cách học tập của Kolb dưới dạng ma trận 2×2. Mỗi phong cách học tập đại diện cho sự kết hợp của hai phong cách ưa thích.</p>



