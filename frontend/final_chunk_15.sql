<h2 class="wp-block-heading">Những lời chỉ trích về phương pháp: Ưu và nhược điểm của Khung</h2>



<p>Vì vậy, những ưu điểm và nhược điểm của Mô hình tìm hiểu đánh giá nói chung là gì?&nbsp;May mắn thay, những người khác trước chúng tôi đã xem xét tài liệu nên chúng tôi có thể tự rút ra kết luận (Drew &amp; Wallis, 2014).&nbsp;Trước tiên hãy nhìn vào chuyên gia.</p>



<h3 class="wp-block-heading">Ưu điểm tiềm năng của AI</h3>



<ul class="wp-block-list">
<li>Đầu tiên, AI tập trung vào các điểm mạnh, được cho là cung cấp năng lượng cho các tổ chức để thay đổi và đổi mới tích cực (Ludema và cộng sự, 2006; Bright, 2009);</li>



<li>Việc tận dụng điểm mạnh cũng cho phép nhân viên nâng cao trình độ của mình (Linley và cộng sự, 2010);</li>



<li>Nó khuyến khích văn hóa học tập thông qua tìm hiểu tập thể và trang bị cho mọi người những kỹ năng để tự khám phá (Conklin &amp; Hartman, 2014);</li>



<li>Vì vậy, nó khuyến khích tư duy sáng tạo, ý tưởng và có khả năng thúc đẩy các phương pháp tiếp cận đổi mới (Cooperrider &amp; Srivastva, 1987; Cooperrider và cộng sự, 2008);</li>



<li>Ngược lại, những điều này tạo điều kiện thuận lợi cho khả năng thích ứng của tổ chức – một lợi thế cạnh tranh quan trọng trong môi trường kinh doanh năng động (Basadur, 2004);</li>



<li>Văn hóa học tập cũng khuyến khích sự thay đổi bền vững (Boyce, 2003);</li>



<li>Về mặt thiết kế, nó nhằm mục đích khuyến khích sự tham gia của các bên liên quan (Drew &amp; Wallis, 2014);</li>



<li>Thông qua sự tham gia, nó tìm cách thúc đẩy sự cam kết hơn là phản kháng (Lines, 2004; Drew &amp; Wallis, 2014);&nbsp;Và</li>



<li>Khung 4D, thông qua cấu trúc của nó, cho phép mọi người hiểu rõ hơn về hành động (Bright, 2009).</li>
</ul>



<p>Có một chủ đề nhất quán trong phần lớn những lợi thế tiềm năng này;&nbsp;đây là câu hỏi Đánh giá cao đề cập đến sự thay đổi ở cấp độ văn hóa, thay vì trình bày cách tiếp cận phân tích để &#8216;khắc phục&#8217; các vấn đề cụ thể.</p>



<p>Thật vậy, AI khuyến khích cách tiếp cận hệ thống toàn diện, tiền đề cơ bản của nó không phải là &#8216;từ trên xuống&#8217; hay &#8216;từ dưới lên&#8217; (Davidcooperrider.com, 2019).</p>



<p>Theo hướng đó, chúng ta hãy xem xét những nhược điểm tiềm ẩn của phương pháp Điều tra đánh giá cao.</p>



<h3 class="wp-block-heading">Nhược điểm tiềm ẩn của AI</h3>



<ul class="wp-block-list">
<li>AI cần có thời gian đáng kể—nó không phải là cách khắc phục nhanh chóng bằng sức tưởng tượng (Drew &amp; Wallis, 2014);</li>



<li>Thay đổi tổ chức quy mô lớn thông qua AI có thể tiêu tốn nhiều tài nguyên, đặc biệt nếu những người tham gia bị phân tán về mặt địa lý, như trường hợp nghiên cứu ở trên;</li>



<li>Nó phụ thuộc rất nhiều vào mức độ có thể tạo ra một môi trường chia sẻ tích cực, hỗ trợ và cởi mở (Cooperrider &amp; Whitney, 1999; Ludema và cộng sự, 2003);</li>



<li>Không phải tất cả các bên liên quan luôn có thể tham gia một cách thực tế (Schooley, 2012);&nbsp;Và</li>



<li>Nếu tất cả các bên liên quan không thể tham gia, điều này sẽ đặt ra câu hỏi xung quanh đạo đức đạo đức của việc lập chiến lược với những gì về cơ bản không phải là sự đồng thuận dân chủ (Schooley, 2012).</li>
</ul>



<p>Do đó, để tổng hợp những điểm yếu, Drew và Wallis (2014) cho rằng việc lập kế hoạch cẩn thận trở nên quan trọng khi chúng ta xem xét sử dụng AI trong các bối cảnh cụ thể.&nbsp;Schooley (2012) sẽ nhấn mạnh rằng các ứng dụng AI của chính phủ và khu vực công có thể đặc biệt có vấn đề.</p>



<h2 class="wp-block-heading">SOAR là gì?</h2>



<p>Tóm lại, SOAR là một khuôn khổ chiến lược dựa trên các nguyên tắc AI.&nbsp;Sự song song đơn giản nhất với một mô hình được biết đến rộng rãi hơn sẽ là SWOT.</p>



<p>Cả hai đều liên kết các yếu tố nội bộ của công ty với các yếu tố bên ngoài và tương lai tiềm năng để cho phép áp dụng cách tiếp cận mang tính phân tích đối với chiến lược.</p>



<h3 class="wp-block-heading">Khung SOAR</h3>



<p>SOAR là viết tắt của (Stavros và cộng sự, 2003):</p>



<ul class="wp-block-list">
<li>Strengths (Điểm mạnh) – Tương tự như điểm mạnh SWOT, những điểm mạnh này liên quan đến các yếu tố bên trong hiện có.&nbsp;Chúng có thể là nguồn lực nội bộ, động lực hoặc thậm chí các khía cạnh của cơ cấu tổ chức có thể được tận dụng một cách chiến lược để đạt được lợi thế cạnh tranh;</li>



<li>Opportunities (Cơ hội) – Đây là những yếu tố bên ngoài tồn tại trong môi trường kinh tế vĩ mô, ngành hoặc thị trường của công ty;</li>



<li>Aspirations (Khát vọng) – Khát vọng là những tương lai tiềm năng tích cực cho công ty, bao gồm cả cách công ty có thể tạo ra giá trị.&nbsp;Lý tưởng nhất là những điều này có thể liên quan chặt chẽ đến tầm nhìn chiến lược của công ty và lý tưởng nhất là cam kết tập thể có thể được khuyến khích xung quanh tầm nhìn này;&nbsp;Và</li>



<li>Results (Kết quả) – Đây có thể được coi là sản phẩm có thể bàn giao và cho phép thực hiện cũng như đánh giá tiến trình của công ty khi công ty hướng tới mục tiêu của mình.</li>
</ul>



<p>Dưới đây là phiên bản điều chỉnh của ứng dụng ví dụ SOAR của Stavros và cộng sự (2003).&nbsp;Tại đây, có thể thấy&nbsp;<em>các Yếu tố bên trong</em>&nbsp;và&nbsp;<em>Yếu tố bên ngoài</em>&nbsp;(từ SWOT) được thay thế như các danh mục hoạch định chiến lược bằng&nbsp;<em>Điều tra chiến lược</em>&nbsp;và&nbsp;<em>Ý định đánh giá cao</em>&nbsp;trong SOAR.</p>



<figure class="wp-block-table"><table><tbody><tr><td><em></em><em>Điều&nbsp;</em><em>tra chiến lược</em><br><em></em></td><td>Điểm mạnh<br>Tài sản lớn nhất của chúng ta là gì?</td><td>Cơ hội<br>Cơ hội thị trường tốt nhất có thể là gì?</td></tr><tr><td><em>Ý định đánh giá cao</em></td><td>Khát vọng<br>Tương lai ưa thích của chúng ta là gì?</td><td>Kết quả Kết<br>quả có thể đo lường được là gì?</td></tr></tbody></table></figure>



<p>Nguồn: Chuyển thể từ Stavros et al.&nbsp;(2003: 11; 12)</p>



<h3 class="wp-block-heading">SOAR so với SWOT</h3>



<p>Như chúng ta mong đợi từ khung AI, mô hình SOAR bắt đầu bằng việc tìm hiểu.&nbsp;Đây là giai đoạn đầu tiên trong bốn giai đoạn mà người tham gia có thể trải qua với tư cách là một nhóm (Stavros và cộng sự, 2003):</p>



<p><strong>1. Tìm hiểu</strong>: Các câu hỏi tích cực được đặt ra để khám phá những điểm mạnh và nguyện vọng của tổ chức, đồng thời đây là cơ hội tốt để thảo luận cởi mở, tích cực về những hiểu biết chung (hoặc không) về các giá trị và tầm nhìn (Stavros và cộng sự, 2003).</p>



<p>Chúng ta muốn ở đâu?&nbsp;Những điểm mạnh nào đã giúp chúng ta đạt được vị trí hiện tại?&nbsp;Như thế nào và tại sao?</p>



<p><strong>2. Trí tưởng tượng</strong>: Người tham gia nghĩ ra những tương lai tiềm năng.&nbsp;Tầm nhìn, giá trị và sứ mệnh được đồng sáng tạo và việc lặp lại có thể là một phương tiện hữu ích để làm rõ hoặc tái khẳng định định hướng chiến lược của công ty.</p>



<p>Trọng tâm của giai đoạn tưởng tượng là các mục tiêu dài hạn cho một tương lai tốt đẹp hơn là chủ động quản lý rủi ro với các mối đe dọa hoặc điểm yếu trong tâm trí.</p>



<p><strong>3. Đổi mới</strong>: Các mục tiêu chiến lược dài hạn được chia thành các mục tiêu ngắn hạn và phương pháp để đạt được chúng.&nbsp;Đối với một dự án cụ thể, điều này có thể liên quan đến việc phát triển các sản phẩm và khung thời gian;&nbsp;theo nghĩa tổng quát hơn, đó là việc đưa ra các hệ thống để hỗ trợ việc thực hiện.</p>



<p><strong>4. Truyền cảm hứng</strong>: Stavros và các đồng nghiệp giới thiệu&nbsp;Inspire&nbsp;như một giải pháp thay thế cho những gì được coi là hệ thống kiểm soát theo truyền thống (tức là trong trang web văn hóa hoặc trong Quản lý chất lượng toàn diện).</p>



<p>Trong chiến lược thông thường, những điều này có thể đề cập đến KPI và các biện pháp khuyến khích;&nbsp;trong SOAR, truyền cảm hứng bao gồm các hệ thống khuyến khích sự công nhận và khen thưởng đích thực.</p>



<h3 class="wp-block-heading">Áp dụng SOAR</h3>



<p>Tất nhiên, hiểu một framework không giống như đưa nó vào hoạt động.&nbsp;Để đạt được mục tiêu đó, Stavros và Hinrichs (2009) phác thảo một số bước để áp dụng khung SOAR trong&nbsp;<em>Cuốn sách mỏng về bay cao</em>&nbsp;của họ.&nbsp;9 bước của họ như sau:</p>



<ol class="wp-block-list">
<li>Xác định các bên liên quan – Xác định ai sẽ tham gia vào hoạt động này và quyết định cách thức họp.&nbsp;Để phù hợp với mục tiêu hợp tác, toàn diện của AI, những người tham gia phải là các bên liên quan nội bộ đại diện cho các lĩnh vực khác nhau của công ty.</li>



<li>Thiết kế cuộc phỏng vấn AI của bạn – Lên kế hoạch cho các câu hỏi mà bạn định sử dụng;&nbsp;tất nhiên, những điều này sẽ nhằm mục đích phát triển cái nhìn sâu sắc hơn về cốt lõi tích cực của tổ chức.&nbsp;Hiểu được điểm mạnh, thành công và khát vọng của nó là động lực chính, vì vậy câu hỏi của bạn phải phản ánh những mục tiêu này.</li>



<li>Thu hút các bên liên quan – Những hoạt động này sẽ luôn có sự tham gia của các bên liên quan nội bộ và cũng có thể bao gồm các bên liên quan bên ngoài như đối tác, khách hàng hoặc nhà cung cấp nếu thấy phù hợp.&nbsp;Sử dụng câu hỏi của bạn để khám phá những khả năng và tương lai tiềm năng tích cực.</li>



<li>Điều chỉnh lại vấn đề – Các vấn đề sẽ luôn nảy sinh để thảo luận;&nbsp;Cuộc điều tra SOAR tập trung vào sự tập trung tích cực, vì vậy hãy định hình lại các cuộc trò chuyện để xem xét các kết quả mong muốn thay vì tránh né hoặc giảm thiểu các mối đe dọa.</li>



<li>Tóm tắt – Đây là việc làm rõ và khẳng định điểm mạnh của tổ chức – cốt lõi tích cực của tổ chức.</li>



<li>Thiết lập nguyện vọng và xác định kết quả – Đây là một phần quan trọng trong việc xác định hoặc xác định lại tầm nhìn tương lai của tổ chức, điều này lý tưởng sẽ tận dụng những điểm mạnh mà bạn đã xác định chung.&nbsp;Những thứ này sẽ trông như thế nào?&nbsp;Họ sẽ như thế nào?</li>



<li>Đánh giá cơ hội – Nhìn vào những cơ hội đã được tạo ra.&nbsp;Đó là những gì mong muốn nhất?&nbsp;Cái nào mới, sáng tạo và đầy tiềm năng?</li>



<li>Mục tiêu thủ công – Mục tiêu phải xuất phát từ các cơ hội được xác định ở giai đoạn trước.&nbsp;Chúng có thể được liên kết với kết quả để có thể theo dõi và đánh giá tiến độ.&nbsp;Sử dụng các tuyên bố mục tiêu để rõ ràng hơn.</li>



<li>Tạo kế hoạch hành động – Chúng ta sẽ làm việc như thế nào để hướng tới những mục tiêu này?&nbsp;Các kế hoạch hành động cần tạo điều kiện thuận lợi cho việc thực hiện và có thể có kế hoạch cụ thể cho từng mục tiêu.</li>
</ol>



<p>Được triển khai đúng cách với sự tham gia của một nhóm các bên liên quan, khuôn khổ SOAR có mục đích lý tưởng là khuyến khích cam kết tập thể đối với tầm nhìn chung đã xuất hiện (Stavros &amp; Hinrichs, 2009).</p>



