<p>Với vị trí địa lý kỳ lạ dưới hang động, lịch sử lâu đời cùng văn hóa chùa Thái Lan, ngôi chùa này có một kiến trúc khá độc đáo. Nhưng pho tượng Phật ở đây được khắc cá tinh tế, tuy lâu đời nhưng vẫn còn nguyên vẹn. Đặc biệt là những bức tượng bồ tát nghìn mắt nghìn tay hay pho tượng Phật Di Lặc nặng hơn 22 tấn.</p>



<p>Ngôi chùa Hang ở Kiên Giang nổi tiếng linh thiêng vừa mang nét kiến trúc và văn hóa chùa chiềng người xưa lưu truyền lại. Nó đan xen giữa sự hình thành của tự nhiên và sự thiết kế con người. Thể hiện một sắc thái độc đáo của kiến trúc văn hóa vùng Kiên Giang.</p>



