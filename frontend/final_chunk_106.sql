<h3 class="wp-block-heading">Quan niệm về điềm phúc của loài dơi</h3>



<p>Trong quan điểm tứ linh của người Hoa kinh doanh thì phải là Long Lân Bức Phụng. Bức ở đây chỉ loài dơi. Quy chỉ phù hợp với người làm quan, với thương gia, loài dơi khá chậm chạp không thích hợp vận làm ăn.</p>



<p>Khi con dơi treo ngược trên cành cây, thân hình chúng tương ứng với chữ Phúc. Người ta cho rằng đó là biểu tượng phúc đáo, phúc vào nhà nên dơi luôn là điềm đại cát đại lợi. Đặc biệt những loài dơi ở chùa dơi luôn rất gần gũi với con người.</p>



