<p>Đến chùa Dơi bạn có thể mua các loại khô khác nhau trước cổng chùa. Vì là chùa Khmer nên thường sư ở đây sẽ không ăn chay. Quan niệm ở chùa Khmer là người dân cho gì họ sẽ ăn đó chứ không lựa chọn.</p>



<figure class="wp-block-image"><img loading="lazy" decoding="async" width="1024" height="853" src="https://media.huynhhieutravel.com/trên-trần-là-những-hình-vẽ-về-cuộc-đời-đức-Phật-1024x853.jpg" alt="Trên trần là những hình vẽ về cuộc đời đức Phật" class="wp-image-3467"/><figcaption>Trên trần là những hình vẽ về cuộc đời đức Phật</figcaption></figure>



<p>Bạn cũng có thể thưởng thức những trái dừa nước trái nhỏ ở trước cổng chùa. Trưa nắng oi bức, tham quan chùa Dơi rồi làm một quả dừa mát lạnh thì thật tuyệt vời. Dừa ở đây vị ngọt, thanh, uống vào rất mát.</p>



