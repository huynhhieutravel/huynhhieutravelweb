<h3 class="wp-block-heading">Chuyện về loài heo năm mống</h3>



<p>Heo năm mống hay heo &#8220;ba giò&#8221; là những thứ linh thiêng mà người dân Khmer sợ hãi khi nhắc đến. Heo ba giò ở đây không phải là chỉ có ba chiếc giò mà là 3 giò có một màu và giò còn lại có màu khác</p>



<figure class="wp-block-image"><img loading="lazy" decoding="async" width="1024" height="853" src="https://media.huynhhieutravel.com/chùa-dơi-tỉnh-sóc-trăng-1024x853.jpg" alt="Chùa Dơi tỉnh Sóc Trăng" class="wp-image-3457"/><figcaption>Chùa Dơi tỉnh Sóc Trăng</figcaption></figure>



<p>Người Khmer quan niệm, con heo nào mang yếu tố như vậy là cốt tinh của người. Kiếp trước người đó làm nhiều điều ác nên đầu thay thành heo năm mống. Người ở đây quan niệm heo năm mống là những linh hồn ác kiếp trước. Nên khi nuôi chúng, gia đình đó phải chịu tai kiếp và xui xẻo. Nhưng nếu giết chúng thì gia đình sẽ gặp điều bất hạnh to lớn hoặc có thể chết đi.</p>



<figure class="wp-block-image"><img loading="lazy" decoding="async" width="1024" height="853" src="https://media.huynhhieutravel.com/cổng-chùa-dơi-1024x853.jpg" alt="Cổng chùa Dơi" class="wp-image-3458"/><figcaption>Cổng chùa Dơi</figcaption></figure>



<p>Chính vì vậy, đưa heo năm mống vào chùa để giải tai ương là điều mà bà con xung quanh hay làm. Họ mong với phúc đức của chùa sẽ giải đi linh hồn tội lỗi và giúp cốt tinh đó nhanh đầu thai thành người. Hàng ngày, những con heo đó được nghe những kinh kệ, sám hối nơi cửa Phật. Nó sẽ không còn đi mang tai họa đến người khác nữa. Từ đó chùa Dơi trở thành nơi nuôi dưỡng những con heo quái dị cho người dân.</p>



