<p>Đặc biệt, Sóc Trăng là vùng nhiều vườn trái cây. Nhưng không hiểu sao loài dơi thường chỉ thích ở trong chùa Dơi. Chúng ít khi ăn trái cây trong vườn. Cứ vào khoảng 6h00 &#8211; 7h00 chúng bay ra ngoài vườn xa để kiếm ăn. Khi bay, chúng thường bay vòng qua chánh điện chứ hiếm khi bay thẳng ngang đó. Dường như có điềm linh thiêng bao bọc lấy ngôi chùa và chúng vô cùng kính ngưỡng.</p>



