<p>Một hôm khi quét dọn, bà Khiên mệt mỏi nên ngủ thiếp đi bên cửa chùa. Bà Khiên năm mơ thấy Bồ Tát hiển linh báo mộng. Nói rằng ngày hôm sau, sẽ có một cô gái đến xin quy y, nương nhờ cửa Phật để tu tâm. Bà Khiên sau khi tỉnh giấc, đã thắp nhang và mong chờ vị nữ thí chủ sẽ đến vào ngày hôm sau.</p>



