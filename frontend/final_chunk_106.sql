<h2 class="wp-block-heading">Kiến trúc chùa Dơi Sóc Trăng</h2>



<p>Chùa Dơi ở Sóc Trăng là một ngôi chùa Khmer điển hình. Tổng thể kiến trúc chùa bao gồm: Chánh điện, Sala, phòng các thầy sư và phòng tín đồ, phòng trụ trì, phòng các vị sư khác, phòng khách, tháp để tro cốt người, nghĩa địa, hồ nước và cả một khu vườn lớn. Khu vườn cũng là nơi trú chân của hàng nghìn con dơi ngựa của chùa.</p>



<figure class="wp-block-image"><img loading="lazy" decoding="async" width="1024" height="853" src="https://media.huynhhieutravel.com/khuôn-viên-chùa-dơi-khá-nhiều-cây-xanh-1024x853.jpg" alt="Khuôn viên chùa dơi khá nhiều cây xanh" class="wp-image-3460"/><figcaption>Khuôn viên chùa dơi khá nhiều cây xanh</figcaption></figure>



<p>Chánh điện được xây bằng gạch, mái ngói được lợp cong vút lên cao với hình tượng rắn naga, đỉnh mái là tháp nhọn. Xung quanh chánh điện là các cột hình tiên nữ Kemmar chấp hai tay trước ngực. </p>



<figure class="wp-block-image"><img loading="lazy" decoding="async" width="1024" height="853" src="https://media.huynhhieutravel.com/mái-chánh-điện-chùa-dơi-được-thiết-kế-đặc-biệt-1024x853.jpg" alt="Mái chánh điện chùa Dơi được thiết kế đặc biệt" class="wp-image-3463"/><figcaption>Mái chánh điện chùa Dơi được thiết kế đặc biệt</figcaption></figure>



<p>Bên trong chánh điện là pho tượng Phật bằng đá ngồi trên tòa sen cao khoảng 2m và một pho tượng khác mô tả đức Phật cưỡi trên thần rắn Muchalinda. Trên 4 bức tường là những hình vẽ mô tả về cuộc đời đức Phật. Từ khi sinh ra đến lúc người lớn lên, chiêm nghiệm cuộc đời và ngồi dưới gốc cây bồ đề niết bàn thành Phật.</p>



<figure class="wp-block-image"><img loading="lazy" decoding="async" width="1024" height="853" src="https://media.huynhhieutravel.com/cảnh-đức-Phật-bước-bảy-bước-nở-bảy-hoa-sen-1024x853.jpg" alt="Cảnh đức Phật bước bảy bước nở bảy hoa sen" class="wp-image-3446"/><figcaption>Cảnh đức Phật bước bảy bước nở bảy hoa sen</figcaption></figure>



<p>Mỗi một bảo tháp ở sân chùa đều chứa các di hài của trụ trì đời trước. Sala là kiểu nhà rông, là nơi nghỉ ngơi và tu học riêng tư của các sư. Phía sau vườn là những ngôi mộ heo năm mống mà tôi đã kể về sự tích của chúng ở trên. Chùa cũng còn nuôi một số con heo năm mống trong khuôn viên.</p>



<figure class="wp-block-image"><img loading="lazy" decoding="async" width="1024" height="853" src="https://media.huynhhieutravel.com/cảnh-đức-phật-quyết-cắt-tóc-tham-ngộ-con-đường-giải-thoát-1024x853.jpg" alt="Cảnh đức Phật quyết cắt tóc tham ngộ con đường giải thoát" class="wp-image-3447"/><figcaption>Cảnh đức Phật quyết cắt tóc tham ngộ con đường giải thoát</figcaption></figure>



<p>Cổng chùa được xây nhìn về hướng Tây Bắc, trang trí cách điệu với họa tiết cánh sen và hoa cà ri được cách điệu. Xung quanh sân vườn có nhiều cây cổ thụ được trồng. Buổi trưa rợp bóng mát, mỗi lần gió thổi ngang lại rì rào như đang hát ca.</p>



