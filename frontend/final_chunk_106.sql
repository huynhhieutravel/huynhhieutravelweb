<p>Từng có lúc những con dơi ở đây luôn đi theo một vị Đại Đức chủ trì chùa. Ông xem chúng như là những người bạn yêu quý. Những con dơi đó đôi khi ngủ lại cả trong phòng ông. Hàng ngày nghe tụng kinh gõ mõ.</p>



