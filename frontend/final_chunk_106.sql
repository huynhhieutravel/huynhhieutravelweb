<p>Dơi là loài vật thiêng liêng, mang ý nghĩa đặc biệt theo quan niệm thời xưa.</p>



<h3 class="wp-block-heading">Đặc điểm loài dơi ở chùa Dơi (Mahatup)</h3>



<p>Dơi ở chùa gồm hai loại là dơi ngựa Thái Lan và <a rel="noreferrer noopener nofollow" aria-label="dơi ngựa (mở trong tab mới)" href="https://vi.wikipedia.org/wiki/D%C6%A1i_qu%E1%BA%A1_l%E1%BB%9Bn" target="_blank">dơi ngựa</a> lớn. Chúng sống ở đây từ trước cả lúc xây chùa. Hiện những loài dơi này đã được đưa vào sách đỏ Việt Nam và nghiêm cấm săn bắt.</p>



<figure class="wp-block-image"><img loading="lazy" decoding="async" width="1024" height="853" src="https://media.huynhhieutravel.com/chùa-dơi-sóc-trăng-có-sân-vườn-rộng-rãi-1024x853.jpg" alt="Chùa dơi Sóc Trăng có sân vườn rộng rãi" class="wp-image-3456"/><figcaption>Chùa dơi Sóc Trăng có sân vườn rộng rãi</figcaption></figure>



<p>Khối lượng những con dơi ngựa ở đây từ 500gr &#8211; 1100gr/con. Cách của chúng khi căng ngang có chiều dài 1,1m đến 1,5m. Tốc độ tối đa khi bay có thể lên đến 50 &#8211; 60km/h. Chúng là loài động vật có vú, miệng có răng bén để gặm trái cây và miệng nhọn như loài chó phốc. Chân chúng có 5 ngón và nhọn như hình móc câu, chân chúng khá là khỏe. Khi ngủ, chúng móc chân vào cành cây và treo ngược lủng lẳng lên thân cây.</p>



