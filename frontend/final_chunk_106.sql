<p>Thế là bà biết rằng vị nữ thí chủ mà Bồ Tát nói đến chính là nàng heo này. Mọi người cũng bảo rằng đó là điềm báo của Phật để giải nghiệp oán cho nàng heo. Thế là mọi người cùng bà Khiên bắt đầu làm lễ nhận nàng heo năm móng quy y đúng như nghi lễ. Đặt tên pháp danh cho nàng heo này là &#8220;Năm Hợi&#8221;. Và cũng từ đó, sau này những người dân làng xung quanh hễ có heo năm móng sinh ra đều dẫn lại chùa nhờ nuôi.</p>



