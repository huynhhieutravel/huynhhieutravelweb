<p>Sau này khi Năm Hợi chết, các sư thầy cho mai táng sau chùa như thủ tục người chết bình thường. Mọi người dân khi hay tin đều đến đốt nhang cúng viếng cô. Một ngày sau, bỗng có một người phụ nữ đến từ Sài Gòn tìm đến chùa. Người phụ nữ bảo rằng mẹ cô sau khi mất đã tìm về báo tin rằng bà đã hóa thành kiếp heo. Hiện đã trả xong nghiệp báo và đầu thai.</p>



<p>Người phụ nữ đó mong các sư cho phép làm lễ cầu siêu để linh hồn mẹ cô đầu thai an lành. Sau khi cầu siêu xong, người phụ nữ đã cho lập bia, vẽ hình một chú heo lên và đề tên Năm Hợi vào bia mộ. Sau này khi có heo chết, những người nhà gửi heo đều học theo làm bia mộ cho những chú heo năm móng đó. Phía sau chùa Dơi xuất hiện một nghĩa địa heo năm móng là như vậy.</p>



