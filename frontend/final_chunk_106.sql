<p>Sáng hôm sau, bà Khiên dậy sớm trông chờ. Nhưng lạ thay, hôm đó cửa chùa vẫn vắng khách. Không có người nào đến xin quy y cửa phật. Bà Khiên cho rằng mình đã nằm mơ không linh. Chiều tối đến, bà cầm chổi quét dọn sân chùa và làm sạch cỏ dạy như thường lệ. Bất ngờ thay bà phát hiện phía sau vườn là một con heo cái năm mống đang nằm ngủ ngon lành.</p>



