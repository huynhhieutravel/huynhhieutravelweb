<p>Đến ngày 11 thì bắt đầu đông đúc dần. Lễ cầu an cũng được tiến hành vào tối ngày 11. Các vị sư từ các chùa chiềng gần đó cũng tề tụ. Họ tụng kinh cầu quốc thái dân an, mong một mùa vụ đi biển bội thu và bình an. Lễ tụng kinh thường diễn ra đến nữa đêm. Bên ngoài Dinh Cậu, người dân cũng bắt đầu tổ chức những lễ hội hoa đăng náo nhiệt. Những ngọn đèn lớn và hoa đăng sáng rực khắp đường và bờ biển. Tiếng trống, lễ hội và âm nhạc khá linh đình, đôi khi còn có cả múa lân.</p>



<figure class="wp-block-image"><img loading="lazy" decoding="async" width="1024" height="810" src="https://media.huynhhieutravel.com/biển-dinh-cô-1024x810.jpg" alt="Biển Dinh Cô" class="wp-image-4984"/><figcaption>Biển Dinh Cô</figcaption></figure>



<p>Ngày 12 là lúc lễ hội chính diễn ra. Một vị Chánh tế dẫn đoàn từ Dinh Cô tiến về mé biển, tàu thuyền trang hoàng lộng lẫy chờ từ rạng sáng. Sẽ có một đội mặc lễ phục truyền thống, đầu đội mão, chân đi hia, mang kiệu son thếp vàng chở bài vị, có lọng che và quân cờ đi kèm hai bên theo sau. Tiếp sau đó là đoàn nhạc ngũ âm và đoàn chèo bả trạo với những bộ áo quần sặc sở. </p>



<p>Khi đến mé biển, cả đoàn sẽ tiến lên một thuyền lễ lớn được trang hoàng lộng lẫy. Trước mũi thuyền sẽ có hương án sơn đỏ, trên có lư hương và mâm trái cây. Những thành phần chính trong đoàn rước bao gồm Chánh tế sẽ tiến lên thuyền này. Còn lại những người khác sẽ tiến đến những ghe thuyền khác neo đậu gần đó.</p>



<p>Sau màn pháo nổ hoặc hồi chuông, Chánh tế sẽ cho thuyền khởi hành. Những chiếc ghe thuyền phía sau cũng nối đuôi nhau. Tiếng nổ đầu máy kéo hòa cũng tiếng nhạc ngũ cung rình rang. Sau đó là các tiếng trống, chiêng liên hồi nổ ra. Đoàn thuyền mang theo một không khí nhộn nhịp tiến ra vùng biển xanh vào buổi sáng sớm. Các thuyền sẽ tung lên trời các quả bóng bay đủ loại màu sắc, tạo thành một khung cảnh rộn ràng tuyệt vời.</p>



<figure class="wp-block-image"><img loading="lazy" decoding="async" width="1024" height="960" src="https://media.huynhhieutravel.com/toàn-cảnh-dinh-cô-1024x960.jpg" alt="Toàn cảnh Dinh Cô nơi tổ chức lễ hội Nghinh Cô" class="wp-image-4987"/><figcaption>Toàn cảnh Dinh Cô</figcaption></figure>



<p>Sau khi đoàn thuyền đi khoảng 1-2km, vị Chánh tế sẽ cho dừng lại, tạo thành một vòng tròn thuyền rộng. Vị Chánh tế và đội mặc lễ phục sẽ tiến về mũi thuyền làm lễ Nghinh Cô và vái mời Ông Nam Hải về dinh chứng kiến lòng thành của những người dân. Đội nhạc ngũ cung sẽ đệm, đội chèo bả cất tiếng hát, ca ngợi công đức của Cô và Ông Nam Hải. Họ cầu mong một năm mưa thuận gió hòa, bội thu tôm cá.</p>



<p>Sau đó các thuyền sẽ cho nổ pháo và trống hòa nhịp cùng. Tất cả tạo thành một không khí sôi nổi ở giữa biển khơi.</p>



<p>Khi thuyền trở về thì đoàn múa lân ở đất liền sẽ ra nghênh đoán, những người dân bên ngoài sẽ phất cờ, hò reo rình rang. Ngoài những chiếc bóng bay đủ màu sắc thả lên bầu trời thì những người dân hành hương cũng bắt đầu phóng sinh. Họ thả các loài chim lên dày đặc cả bầu trời.</p>



<p>Kiệu rước Cô được đưa thẳng về Dinh Cô, và làm lễ tế. Lễ vật dâng lên Cô bao gồm 1 heo quay, 1 con heo vừa được mổ, bánh trái, hoa quả, rượu trà. Sau đó tiến hành lễ dâng hương, rượu và trà. Tiếp theo là múa Tam hiền và Mâm vàng. Mộ Cô cũng được cúng hoa quả thanh tịnh. Sau lễ chính sẽ là lễ Xây chầu &#8211; Đại bội (Hát bội cả ngày lẫn đêm).</p>



