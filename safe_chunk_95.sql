<p>Đa phần những buổi lễ Dinh Cô đều được giữ gìn các nét truyền thống từ trước đến nay. Tuy vậy vẫn có nhiều thay đổi theo thời đại. Như việc thả bong bóng đủ các màu sắc để trông phần rực rỡ hơn. Hay cũng có những biến chất của việc phóng sinh sau đó là bị người dân bắt lại.</p>



