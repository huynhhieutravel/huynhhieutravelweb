<h2 class="wp-block-heading">Kiến trúc Dinh Cô</h2>



<p>Ban đầu Dinh Cô chỉ là một miếu nhỏ lợp bằng lá cây. Lúc đầu Dinh Cô được xây dựng sát bờ biển. Nhưng năm 1930 có sự tranh chấp chủ quyền đất của người dân, Dinh Cô được dời lên phía triền núi.</p>



<figure class="wp-block-image"><img loading="lazy" decoding="async" width="1024" height="720" src="https://media.huynhhieutravel.com/dinh-cô-1024x720.jpg" alt="Dinh Cô" class="wp-image-4985" srcset="https://media.huynhhieutravel.com/dinh-cô-1024x720.jpg 1024w, https://media.huynhhieutravel.com/dinh-cô-370x260.jpg 370w, https://media.huynhhieutravel.com/dinh-cô-100x70.jpg 100w" sizes="(max-width: 1024px) 100vw, 1024px" /><figcaption>Dinh Cô</figcaption></figure>



<p>Sau này người dân thờ cúng ngày càng nhiều. Vừa để tiện việc thăm viếng cô và tỏ lòng tôn trọng, những người hành hương đã quyên góp xây dựng nên một ngôi miếu khang trang hơn. Diện tích Dinh Cô ước tính khoảng 1.000m2  </p>



<p>Dinh Cô ngày nay được lớp ngói âm dương, có 3 tầng, bậc tam cấp bằng xi măng để đi lên xuống dễ dàng. Mặt trong tựa vào núi Thùy Vân, mặt ngoài nhìn ra biển Long Hải. Mỗi khi những ngư dân có việc đi ngang đây đều dừng lại và thắp nhan ngay trên tàu để cầu mong bình an.</p>



<p>Gian giữa Dinh Cô là tượng Cô, có 4 cô hầu gái đứng chầu hai bên. Bên phải là án thờ Ngũ Vị Nương Nương, bên trái là án thờ Tứ Pháp Nương Nương. Tường bên phải là thờ cha mẹ thân sinh của Cô. Tường bên trái thờ Chúa Cậu. Và gian bên cạnh là thờ Mẹ Sanh.</p>



<p>Ngoài chánh điện, Dinh Cô còn thờ Cửu Thiên Huyền Nữ, Quan Thế Âm Bồ Tát, Bác Hồ, Quan Thánh Đế Quân, Hỏa Tinh Thánh Mẫu, Chúa Tinh Nương Nương,&#8230;</p>



