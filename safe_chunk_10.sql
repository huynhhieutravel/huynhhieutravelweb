<h2 class="wp-block-heading">Những lời chỉ trích về phương pháp: Ưu và nhược điểm của Khung</h2>



<p>Vì vậy, những ưu điểm và nhược điểm của Mô hình tìm hiểu đánh giá nói chung là gì?&nbsp;May mắn thay, những người khác trước chúng tôi đã xem xét tài liệu nên chúng tôi có thể tự rút ra kết luận (Drew &amp; Wallis, 2014).&nbsp;Trước tiên hãy nhìn vào chuyên gia.</p>



<h3 class="wp-block-heading">Ưu điểm tiềm năng của AI</h3>



<ul class="wp-block-list">
<li>Đầu tiên, AI tập trung vào các điểm mạnh, được cho là cung cấp năng lượng cho các tổ chức để thay đổi và đổi mới tích cực (Ludema và cộng sự, 2006; Bright, 2009);</li>



<li>Việc tận dụng điểm mạnh cũng cho phép nhân viên nâng cao trình độ của mình (Linley và cộng sự, 2010);</li>



<li>Nó khuyến khích văn hóa học tập thông qua tìm hiểu tập thể và trang bị cho mọi người những kỹ năng để tự khám phá (Conklin &amp; Hartman, 2014);</li>



<li>Vì vậy, nó khuyến khích tư duy sáng tạo, ý tưởng và có khả năng thúc đẩy các phương pháp tiếp cận đổi mới (Cooperrider &amp; Srivastva, 1987; Cooperrider và cộng sự, 2008);</li>



<li>Ngược lại, những điều này tạo điều kiện thuận lợi cho khả năng thích ứng của tổ chức – một lợi thế cạnh tranh quan trọng trong môi trường kinh doanh năng động (Basadur, 2004);</li>



<li>Văn hóa học tập cũng khuyến khích sự thay đổi bền vững (Boyce, 2003);</li>



<li>Về mặt thiết kế, nó nhằm mục đích khuyến khích sự tham gia của các bên liên quan (Drew &amp; Wallis, 2014);</li>



<li>Thông qua sự tham gia, nó tìm cách thúc đẩy sự cam kết hơn là phản kháng (Lines, 2004; Drew &amp; Wallis, 2014);&nbsp;Và</li>



<li>Khung 4D, thông qua cấu trúc của nó, cho phép mọi người hiểu rõ hơn về hành động (Bright, 2009).</li>
</ul>



<p>Có một chủ đề nhất quán trong phần lớn những lợi thế tiềm năng này;&nbsp;đây là câu hỏi Đánh giá cao đề cập đến sự thay đổi ở cấp độ văn hóa, thay vì trình bày cách tiếp cận phân tích để &#8216;khắc phục&#8217; các vấn đề cụ thể.</p>



<p>Thật vậy, AI khuyến khích cách tiếp cận hệ thống toàn diện, tiền đề cơ bản của nó không phải là &#8216;từ trên xuống&#8217; hay &#8216;từ dưới lên&#8217; (Davidcooperrider.com, 2019).</p>



<p>Theo hướng đó, chúng ta hãy xem xét những nhược điểm tiềm ẩn của phương pháp Điều tra đánh giá cao.</p>



<h3 class="wp-block-heading">Nhược điểm tiềm ẩn của AI</h3>



<ul class="wp-block-list">
<li>AI cần có thời gian đáng kể—nó không phải là cách khắc phục nhanh chóng bằng sức tưởng tượng (Drew &amp; Wallis, 2014);</li>



<li>Thay đổi tổ chức quy mô lớn thông qua AI có thể tiêu tốn nhiều tài nguyên, đặc biệt nếu những người tham gia bị phân tán về mặt địa lý, như trường hợp nghiên cứu ở trên;</li>



<li>Nó phụ thuộc rất nhiều vào mức độ có thể tạo ra một môi trường chia sẻ tích cực, hỗ trợ và cởi mở (Cooperrider &amp; Whitney, 1999; Ludema và cộng sự, 2003);</li>



<li>Không phải tất cả các bên liên quan luôn có thể tham gia một cách thực tế (Schooley, 2012);&nbsp;Và</li>



<li>Nếu tất cả các bên liên quan không thể tham gia, điều này sẽ đặt ra câu hỏi xung quanh đạo đức đạo đức của việc lập chiến lược với những gì về cơ bản không phải là sự đồng thuận dân chủ (Schooley, 2012).</li>
</ul>



<p>Do đó, để tổng hợp những điểm yếu, Drew và Wallis (2014) cho rằng việc lập kế hoạch cẩn thận trở nên quan trọng khi chúng ta xem xét sử dụng AI trong các bối cảnh cụ thể.&nbsp;Schooley (2012) sẽ nhấn mạnh rằng các ứng dụng AI của chính phủ và khu vực công có thể đặc biệt có vấn đề.</p>



<h2 class="wp-block-heading">SOAR là gì?</h2>



<p>Tóm lại, SOAR là một khuôn khổ chiến lược dựa trên các nguyên tắc AI.&nbsp;Sự song song đơn giản nhất với một mô hình được biết đến rộng rãi hơn sẽ là SWOT.</p>



<p>Cả hai đều liên kết các yếu tố nội bộ của công ty với các yếu tố bên ngoài và tương lai tiềm năng để cho phép áp dụng cách tiếp cận mang tính phân tích đối với chiến lược.</p>



<h3 class="wp-block-heading">Khung SOAR</h3>



<p>SOAR là viết tắt của (Stavros và cộng sự, 2003):</p>



<ul class="wp-block-list">
<li>Strengths (Điểm mạnh) – Tương tự như điểm mạnh SWOT, những điểm mạnh này liên quan đến các yếu tố bên trong hiện có.&nbsp;Chúng có thể là nguồn lực nội bộ, động lực hoặc thậm chí các khía cạnh của cơ cấu tổ chức có thể được tận dụng một cách chiến lược để đạt được lợi thế cạnh tranh;</li>



<li>Opportunities (Cơ hội) – Đây là những yếu tố bên ngoài tồn tại trong môi trường kinh tế vĩ mô, ngành hoặc thị trường của công ty;</li>



<li>Aspirations (Khát vọng) – Khát vọng là những tương lai tiềm năng tích cực cho công ty, bao gồm cả cách công ty có thể tạo ra giá trị.&nbsp;Lý tưởng nhất là những điều này có thể liên quan chặt chẽ đến tầm nhìn chiến lược của công ty và lý tưởng nhất là cam kết tập thể có thể được khuyến khích xung quanh tầm nhìn này;&nbsp;Và</li>



<li>Results (Kết quả) – Đây có thể được coi là sản phẩm có thể bàn giao và cho phép thực hiện cũng như đánh giá tiến trình của công ty khi công ty hướng tới mục tiêu của mình.</li>
</ul>



<p>Dưới đây là phiên bản điều chỉnh của ứng dụng ví dụ SOAR của Stavros và cộng sự (2003).&nbsp;Tại đây, có thể thấy&nbsp;<em>các Yếu tố bên trong</em>&nbsp;và&nbsp;<em>Yếu tố bên ngoài</em>&nbsp;(từ SWOT) được thay thế như các danh mục hoạch định chiến lược bằng&nbsp;<em>Điều tra chiến lược</em>&nbsp;và&nbsp;<em>Ý định đánh giá cao</em>&nbsp;trong SOAR.</p>



