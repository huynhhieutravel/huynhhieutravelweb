<p>Các doanh nghiệp thường tập trung vào những gì không hiệu quả và áp dụng tư duy &#8216;nguyên nhân gốc rễ&#8217;, chỉ để thấy mình phải đối mặt với một loạt các câu hỏi khác nhau nhưng có liên quan đến nhau.</p>



<p>Những câu hỏi như “Làm cách nào chúng ta có thể khắc phục tình trạng thiếu gắn kết?“ “Chúng ta phải làm gì với động lực thấp?“ “Hoặc, tại sao mọi người lại không đoàn kết vì mục tiêu chung?”</p>



<p>Mô hình tìm hiểu đánh giá cao là một trong những phương pháp tiếp cận tổ chức tích cực quan trọng đối với sự phát triển và học tập tập thể.</p>



<p>Ở đây, chúng ta xem xét làm thế nào nó đã phát triển thành một trong những phong trào có ảnh hưởng nhất đối với sự phát triển tổ chức tích cực trong những thập kỷ gần đây.</p>



<h2 class="wp-block-heading">Yêu cầu đánh giá cao là gì?</h2>



<p>Điều tra đánh giá cao (Appreciative Inquiry &#8211; AI) là một cách tiếp cận hợp tác, dựa trên thế mạnh để thay đổi trong các tổ chức và các hệ thống con người khác.&nbsp;Do đó, thuật ngữ &#8216;Yêu cầu đánh giá cao&#8217; được sử dụng để chỉ cả hai:</p>



<ul class="wp-block-list">
<li>Mô hình AI – bản thân nó liên quan đến các nguyên tắc và lý thuyết đằng sau cách tiếp cận thay đổi dựa trên điểm mạnh;&nbsp;Và</li>



<li>Phương pháp và sáng kiến ​​AI – là các kỹ thuật và bước vận hành cụ thể được sử dụng để mang lại sự thay đổi tích cực trong hệ thống (Davidcooperrider.com, 2019).</li>
</ul>



<h3 class="wp-block-heading">Các khái niệm chính trong AI</h3>



<p>Ý tưởng cơ bản đằng sau AI là theo thời gian, việc các tổ chức tiếp cận sự thay đổi và tăng trưởng từ góc độ giải quyết vấn đề ngày càng trở nên phổ biến.</p>



<p>Khi các công ty đặt mục tiêu nâng cao hiệu quả, tồn tại, hoạt động tốt hơn và tăng cường khả năng cạnh tranh, những người ủng hộ AI cho rằng đã có sự nhấn mạnh quá mức không lành mạnh vào việc “sửa chữa những gì sai” &#8211; một cách tiếp cận dựa trên thâm&nbsp;hụt.</p>



<p>AI nảy sinh như một thách thức đối với những giả định đã ăn sâu này và đề xuất rằng thay vào đó, các tổ chức có thể hưởng lợi từ cái được gọi là cách tiếp cận&nbsp;dựa trên điểm mạnh&nbsp;hoặc&nbsp;khẳng định&nbsp;(Hammond, 2013).</p>



<p>Ngược lại, cách tiếp cận khẳng định này giả định rằng mỗi hệ thống của con người đều có một&nbsp;<em>điểm mạnh cốt lõi tích cực</em>.</p>



<p>Cốt lõi tích cực này không khác nhiều so với cách chúng ta nhìn nhận sức mạnh của tổ chức trong các tài liệu quản lý thông thường.&nbsp;Về bản chất (và được các tác giả diễn giải một cách lỏng lẻo), chúng có thể bao gồm (Cooperrider &amp; Whitney, 2005):</p>



<ul class="wp-block-list">
<li>Các giá trị, niềm tin và khả năng của tổ chức chúng ta khi nó &#8216;ở trạng thái tốt nhất&#8217;;&nbsp;Và</li>



<li>Sự hiểu biết chung về những gì tạo nên điều tốt nhất của chúng ta.</li>
</ul>



<p>Là một khái niệm trong tâm lý học tổ chức tích cực, AI có lẽ được hiểu rõ nhất bằng cách xem xét sự phát triển của nó theo thời gian.</p>



<h2 class="wp-block-heading">Tóm tắt lịch sử</h2>



<p>Sẽ rất hữu ích khi biết một chút về quản lý khoa học và &#8216;Chủ nghĩa Taylor&#8217; để xem làm thế nào và tại sao AI lại ra đời.</p>



<h3 class="wp-block-heading">Quản lý khoa học</h3>



<p>Hầu hết các nhà lãnh đạo và quản lý tổ chức đều đã biết về quản lý khoa học, nhưng đối với những người chưa biết thì đây là một trường phái tư tưởng nổi lên vào cuối thế kỷ 19.&nbsp;Mục tiêu của Quản lý khoa học là nâng cao hiệu quả của quy trình công việc bằng cách xem xét chúng một cách phân tích và loại bỏ lãng phí.</p>



<p>Vào thời điểm đó, <a href="https://www.britannica.com/biography/Frederick-W-Taylor" target="_blank" rel="noreferrer noopener">Frederick Taylor</a>, một kỹ sư người Mỹ, đã được truyền cảm hứng để áp dụng các kỹ thuật khoa học nghiêm ngặt để phân tích và cải thiện cách mọi người làm việc.&nbsp;Nhìn rộng ra, điều này là thông qua việc tính thời gian, đơn giản hóa và tiêu chuẩn hóa các nhiệm vụ.</p>



<p>Các phương pháp tiếp cận sau đó đã bị chỉ trích nặng nề vì thúc đẩy quan điểm coi doanh nghiệp như một cỗ máy chứ không phải là một thực thể của con người.&nbsp;Một điểm tương đồng thú vị khác là nó đặt trọng tâm khá rõ ràng vào&nbsp;các nguồn lực, hơn là phần&nbsp;con người&nbsp;trong nguồn nhân lực.&nbsp;Một trích dẫn trực tiếp từ chính người đàn ông đó đưa ra một ví dụ:</p>



<blockquote class="wp-block-quote is-layout-flow wp-block-quote-is-layout-flow">
<p>“Trong kế hoạch của chúng tôi, chúng tôi không yêu cầu sự chủ động của nhân viên. Chúng tôi không muốn có bất kỳ sáng kiến ​​nào.&nbsp;Tất cả những gì chúng tôi muốn ở họ là tuân theo những mệnh lệnh mà chúng tôi đưa ra, làm theo những gì chúng tôi nói và làm thật nhanh chóng.”</p>
<cite>(Taylor, 1919)</cite></blockquote>



<h3 class="wp-block-heading">Sửa chửa cỗ máy bị hỏng</h3>



<p>Quản lý khoa học ở dạng ban đầu đã không còn phổ biến trong gần 1 thế kỷ.&nbsp;Tuy nhiên, những người ủng hộ AI chỉ ra rất nhiều bằng chứng cho thấy tư duy &#8216;tập trung vào thâm hụt&#8217; vẫn được áp dụng nhiều trong thực tiễn quản lý và tổ chức (Cooperrider &amp; Srivastva, 1987).</p>



<p>Theo nghĩa này, việc thay đổi tổ chức là về việc xác định, thiết lập và sửa chữa những thứ không hoạt động—được Bushe (2013), một chuyên gia về AI, tóm tắt gọn gàng như “điều tra về những trải nghiệm còn thiếu sót”.</p>



<p>Các ví dụ thường được trích dẫn bao gồm phân tích nhu cầu của tổ chức, xác định vấn đề, phân tích nguyên nhân gốc rễ, v.v.</p>



<h3 class="wp-block-heading">Hướng tới cách tiếp cận dựa trên điểm mạnh</h3>



<p>Để phản ứng lại sự nhấn mạnh quá mức này, AI đã nổi lên như một cách tiếp cận thay thế cho sự thay đổi và phát triển của tổ chức;&nbsp;một cách tiếp cận khẳng định tập trung tìm hiểu xem điều gì đúng, điều gì đang hiệu quả và cách hướng tới tầm nhìn mong muốn (Davidcooperrider.com, 2019).</p>



<figure class="wp-block-image size-full"><img loading="lazy" decoding="async" width="1280" height="720" src="https://media.huynhhieutravel.com/so-sanh-mo-hinh-giai-quyet-van-de-vs-mo-hinh-danh-gia-cao.jpg" alt="So sánh mô hình giải quyết vấn đề và mô hình đánh giá cao" class="wp-image-12125" srcset="https://media.huynhhieutravel.com/so-sanh-mo-hinh-giai-quyet-van-de-vs-mo-hinh-danh-gia-cao.jpg 1280w, https://media.huynhhieutravel.com/so-sanh-mo-hinh-giai-quyet-van-de-vs-mo-hinh-danh-gia-cao-768x432.jpg 768w" sizes="(max-width: 1280px) 100vw, 1280px" /><figcaption class="wp-element-caption">So sánh mô hình giải quyết vấn đề và mô hình đánh giá cao</figcaption></figure>



<p>Như đã lưu ý, Mô hình điều tra đánh giá dựa trên nguyên tắc rằng tương lai tích cực của tổ chức có thể đạt được thông qua sự tham gia tập thể và các phương pháp “khẳng định, ép buộc và đẩy nhanh việc học tập trước” (Cooperrider và cộng sự, 2008).</p>



<p>Còn lâu mới mổ xẻ những sai lầm trong quá khứ và xác định con đường khắc phục phía trước.&nbsp;Xa hơn một chút, tôi sẽ xem xét kỹ hơn về mô hình và lý thuyết một cách chi tiết hơn.</p>



<h2 class="wp-block-heading">Một cái nhìn về David Cooperrider</h2>



<p>David Cooperrider thường được coi là người tiên phong trong Mô hình tìm hiểu đánh giá cao.&nbsp;Tuy nhiên, bản thân mô hình này đã được phát triển trong thập niên 80 bởi cả Cooperrider và Suresh Srivastva, người cố vấn của ông lúc bấy giờ.</p>



<h3 class="wp-block-heading">Sức mạnh của câu hỏi</h3>



<p>Cooperrider mô tả “Ah-Ha!”&nbsp;khoảnh khắc xảy ra khi anh ấy và một đồng nghiệp đang thực hiện nghiên cứu hành động cho một dự án phát triển tổ chức (Bushe, 2013).&nbsp;Cụ thể, nhóm nhận thấy mình đang ở trong bầu không khí ngày càng thù địch và tiêu cực và quyết định thay đổi cách tiếp cận.</p>



<p>Thay vì tìm hiểu xem điều gì không hiệu quả, Cooperrider và đồng nghiệp của ông quyết định hỏi xem điều gì đang hiệu quả &#8211; mặc dù ở một công ty khác (Barrett &amp; Cooperrider, 1990).</p>



<p>Sóng não ở đây là bản thân cuộc điều tra có thể định hình mạnh mẽ cách chúng ta nhìn nhận và phát triển hệ thống con người. Điều đó dẫn đến bằng tiến sĩ của Cooperrider&nbsp;về AI vào năm 1986.</p>



<h3 class="wp-block-heading">Từ nghiên cứu đến phỏng vấn đến phát triển tổ chức</h3>



<p>Những gì Cooperrider thực sự có vào thời điểm này là một cái nhìn sâu sắc có khả năng biến đổi về cách có thể cải thiện nghiên cứu khoa học xã hội định tính.</p>



<p>Nghĩa là, sự thay đổi mô hình cho sự thay đổi tổ chức đã không xảy ra ngay lập tức.&nbsp;<a href="http://www.gervasebushe.ca/Foundations_AI.pdf" target="_blank" rel="noreferrer noopener">Bushe (2013), người trình bày chi tiết</a>&nbsp;hơn về lịch sử của AI, mô tả cách tiếp cận tìm hiểu lần đầu tiên được dạy cho nhân viên để họ có thể lần lượt phỏng vấn các nhân viên khác bằng các phương pháp mới.</p>



<p>Nó đã được đón nhận một cách tích cực vì lợi ích của việc tạo ra ý tưởng nhanh chóng trở nên rõ ràng.</p>



<p>Sau đó, David Cooperrider bắt đầu làm việc với những người khác để khám phá cách áp dụng &#8216;chủ nghĩa xây dựng xã hội&#8217; này vào sự thay đổi tổ chức, cùng những thứ khác.&nbsp;Đến năm 1997, &#8216;mô hình 4D&#8217; mà ông đặt nền móng đã trở thành Mô hình tìm hiểu được đánh giá cao mà chúng ta biết ngày nay.</p>



<h2 class="wp-block-heading">Mô hình và lý thuyết</h2>



<p>Bất kỳ người thực hành phát triển tổ chức nào cũng sẽ biết rằng có rất nhiều khuôn khổ trong lĩnh vực này.&nbsp;Mô hình 4D thường đề cập đến sự trình bày trực quan về 4 bước của sáng kiến ​​AI:</p>



<ul class="wp-block-list">
<li>Discovery (Khám phá);</li>



<li>Dream (Mơ);</li>



<li>Design (Thiết kế);</li>



<li>và Định mệnh (Destiny).</li>
</ul>



<p>Tuy nhiên, bạn sẽ thường thấy bước thứ 5 được thêm vào, đối với Define (Xác định), bước này chỉ liên quan đến những gì David Cooperrider mô tả là chọn một chủ đề khẳng định.&nbsp;Ngược lại, một chủ đề khẳng định là trọng tâm của sự can thiệp của bạn &#8211; có thể có một hoặc có thể có nhiều tiêu điểm.</p>



<p>Ví dụ có thể bao gồm sự hài lòng của khách hàng cao hơn, môi trường làm việc an toàn hơn hoặc mang lại giá trị hiệu quả hơn (Kessler, 2013).</p>



<p>Dưới đây là một ví dụ về Mô hình AI không có phần Xác định.</p>



<figure class="wp-block-image size-full"><img loading="lazy" decoding="async" width="1280" height="720" src="https://media.huynhhieutravel.com/mo-hinh-4d-yeu-cau-danh-gia-cao.jpg" alt="Mô hình 4D yêu cầu đánh giá cao" class="wp-image-12124" srcset="https://media.huynhhieutravel.com/mo-hinh-4d-yeu-cau-danh-gia-cao.jpg 1280w, https://media.huynhhieutravel.com/mo-hinh-4d-yeu-cau-danh-gia-cao-768x432.jpg 768w" sizes="(max-width: 1280px) 100vw, 1280px" /><figcaption class="wp-element-caption">Mô hình 4D yêu cầu đánh giá cao</figcaption></figure>



<h3 class="wp-block-heading">Các bước trong mô hình 4D</h3>



<p>Bước Xác định là một phần quan trọng trong việc xác định các bước sau sẽ diễn ra như thế nào.&nbsp;Kessler (2013) nhấn mạnh tầm quan trọng của việc sử dụng ngôn ngữ truyền cảm hứng để định hình trọng tâm can thiệp của bạn.</p>



<p>Vì vậy, sự hài lòng của khách hàng lớn hơn có thể trở thành điều mà ông mô tả là “<em>truyền cảm hứng cho những khách hàng trung thành cuồng nhiệt</em>”.</p>



<p>Các chủ đề khẳng định hiện đã được thiết lập, đây là các giai đoạn (Ludema và cộng sự, 2006):</p>



<h4 class="wp-block-heading">1. Khám phá</h4>



<p>Trọng tâm trong giai đoạn này là tìm kiếm và xác định những gì mang lại sức sống cho tổ chức.&nbsp;Những thành công trong quá khứ có thể được thảo luận và khám phá, và trong mỗi trường hợp, mục tiêu là trau dồi những gì đã tạo nên chúng.</p>



<p>Đây hoàn toàn là hoạt động tìm hiểu tích cực và các bên liên quan trong nội bộ có thể đặt câu hỏi cho nhau để khám phá điều mà Ludema và các đồng nghiệp gọi là “điều tốt nhất của những gì hiện có”.</p>



<p>Mặc dù điều này tập trung vào việc phát hiện ra điểm mạnh nhưng cũng là một cách hữu ích để chuyển tư duy và vốn từ vựng hiện tại khỏi lối suy nghĩ tập trung vào thiếu sót.</p>



<h4 class="wp-block-heading">2. Giấc mơ</h4>



<p>Giai đoạn Giấc mơ là về việc tưởng tượng ra những tương lai tích cực tiềm tàng cho tổ chức.&nbsp;Bởi vì lý tưởng nhất là có nhiều người tham gia tham gia vào quá trình AI, nên những người này sẽ đại diện cho nhiều quan điểm, ý kiến ​​và hiểu biết khác nhau.</p>



<p>Những câu hỏi tích cực vô điều kiện đã được phát triển sẽ mở ra một cách lý tưởng những tầm nhìn và khả năng sáng tạo, mang tính xây dựng.&nbsp;Thông qua ngôn ngữ và hình ảnh tích cực, những người tham gia cùng nhau tạo ra tương lai và kết quả tích cực.</p>



<h4 class="wp-block-heading">3. Thiết kế</h4>



<p>Đồng sáng tạo tiếp tục trong giai đoạn này, nhưng trọng tâm chuyển sang tranh luận và thảo luận về các khả năng đã được tạo ra.</p>



<p>Mục tiêu là đạt được tầm nhìn hoặc giá trị chung mà nhóm hoặc những người tham gia thấy là có tiềm năng thực sự và tích cực.&nbsp;Do đó, những nguyện vọng cá nhân sẽ được chia sẻ, trong một môi trường lý tưởng là hòa nhập, an toàn và hỗ trợ, nơi mọi người đều cảm thấy được lắng nghe.</p>



<h4 class="wp-block-heading">4. Định mệnh</h4>



<p>Mục tiêu của giai đoạn cuối cùng này (trước đây gọi là Giao hàng) là xây dựng tương lai “thông qua đổi mới và hành động” (Ludema et al., 2006: 158).</p>



<p>Tầm nhìn, hệ thống hoặc cơ cấu đã được thiết kế cam kết sử dụng các phương tiện có thể để đạt được chúng sẽ được hoàn thiện hơn nữa thông qua cam kết của từng cá nhân.</p>



<p>Điều đáng nói là giai đoạn Định mệnh của mô hình 4D không được xác định chặt chẽ về cách tiến hành. Kessler lập luận rằng các cá nhân thực hành và lý thuyết sẽ có cách khuyến khích cấu trúc hoặc ứng biến khác nhau trong giai đoạn này (Kessler, 2013).</p>



<h3 class="wp-block-heading">Nguyên tắc cơ bản của việc điều tra đánh giá cao</h3>



<p>Khi AI ngày càng được ứng dụng rộng rãi hơn, chúng ta cũng đã thấy nhiều thực tiễn tương phản và xung đột được cho là thuộc phạm vi bảo trợ của AI.</p>



<p>Đây là điều mà Bushe (2013) cho là nguyên nhân ban đầu thiếu phương pháp luận chính thức—Giáo sư Cooperrider lúc đầu đã do dự khi xuất bản bất kỳ phương pháp nào.&nbsp;Nhưng vào đầu thập kỷ trước, ông và Tiến sĩ Diana Whitney từ Viện Taos đã phát triển 5 nguyên tắc thực hành AI.</p>



<h4 class="wp-block-heading">1. Nguyên tắc xây dựng</h4>



<p>Điều này thừa nhận rằng niềm tin chủ quan của chúng ta về điều gì là đúng sẽ quyết định hành động, suy nghĩ và hành vi của chúng ta.</p>



<p>Ngôn ngữ mà chúng tôi sử dụng hàng ngày có vai trò then chốt trong cách chúng tôi cùng xây dựng tổ chức của mình và điều này bao gồm cả ngôn ngữ chúng tôi sử dụng để tìm hiểu.</p>



<p>Bản thân việc tìm hiểu là việc tạo ra và truyền cảm hứng cho những ý tưởng, tầm nhìn và câu chuyện mới có khả năng dẫn đến hành động (Cooperrider &amp; Whitney, 1999).</p>



<h4 class="wp-block-heading">2. Nguyên tắc đồng thời</h4>



<p>Điều này cho thấy rằng những tìm hiểu của chúng ta về hệ thống của con người có thể khiến chúng thay đổi. Những câu hỏi đầu tiên chúng tôi hỏi có thể định hình cách mọi người suy nghĩ và thảo luận về mọi thứ;&nbsp;đến lượt nó, điều này ảnh hưởng đến cách họ học hỏi và khám phá mọi thứ.</p>



<p>Không có cái gọi là câu hỏi trung lập, theo nghĩa là những câu hỏi nhiệt tình và kiên trì theo những hướng cụ thể sẽ dẫn đến sự thay đổi theo những hướng đó (Cooperrider &amp; Whitney, 1999; Whitney &amp; Trosten-Bloom, 2003).</p>



<h4 class="wp-block-heading">3. Nguyên tắc thơ ca</h4>



<p>Nguyên tắc thứ ba cho rằng chúng ta có thể chọn – hoặc không – nghiên cứu đời sống tổ chức để tạo ra sự khác biệt.&nbsp;Cuộc sống trong các hệ thống của con người, chẳng hạn như các tổ chức và đội nhóm, được đồng tác giả và kể trong các câu chuyện.</p>



<p>Sự lựa chọn từ vựng của chúng ta có thể khơi dậy cảm xúc, hình ảnh, khái niệm và sự hiểu biết, còn AI thì sử dụng câu hỏi để tạo ra những tầm nhìn tích cực, lạc quan về tương lai nhằm truyền cảm hứng và đánh thức &#8216;những điều tốt đẹp nhất trong con người&#8217; (Cooperrider &amp; Whitney, 1999; Kessler, 2013 ).</p>



<h4 class="wp-block-heading">4. Nguyên tắc đoán trước</h4>



<p>Nguyên tắc dự đoán gợi ý rằng hành động và hành vi hiện tại của chúng ta được định hình bởi tầm nhìn của chúng ta về tương lai.</p>



<p>Thông qua AI, chúng ta có thể tạo ra những hình ảnh và tầm nhìn tích cực về tương lai của chúng ta hoặc của tổ chức, điều này sẽ tác động đến những gì chúng ta làm trong hiện tại (Goleman, 1987; Cooperrider &amp; Whitney, 1999).</p>



<h4 class="wp-block-heading">5. Nguyên tắc tích cực</h4>



<p>Điều này thừa nhận rằng để khuyến khích động lực, chúng ta phải đặt những câu hỏi tích cực nhằm nhấn mạnh cốt lõi tích cực của một tổ chức.&nbsp;Sự thay đổi lâu dài phụ thuộc vào sự kết nối xã hội và ảnh hưởng tích cực giữa mọi người.</p>



<p>Những cảm xúc tích cực như sự nhiệt tình, gắn kết, hy vọng và hạnh phúc khuyến khích những ý tưởng sáng tạo và cởi mở với những ý tưởng đổi mới (Barrett &amp; Fry, 2005; Stavros &amp; Torres, 2005).</p>



<blockquote class="wp-block-quote is-layout-flow wp-block-quote-is-layout-flow">
<p>5 nguyên tắc AI này được trích dẫn phổ biến nhất và hiện đã được thiết lập vững chắc.&nbsp;Tuy nhiên, khi phương pháp Điều tra đánh giá ngày càng trở nên phổ biến hơn, chúng ta đang thấy những nguyên tắc mới nổi đang được đề xuất.</p>



<p>Trong số này có các nguyên tắc như tính trọn vẹn, ban hành, nhận thức, tự do lựa chọn, tường thuật và tính đồng bộ (Whitney &amp; Trosten-Bloom, 2003; Stratton-Berkeessel &amp; Myers, 2019).</p>
</blockquote>



<h2 class="wp-block-heading">Ví dụ về phương pháp tiếp cận</h2>



<p>Trong phần này, chúng ta sẽ xem xét sâu hơn một ví dụ về AI được ứng dụng để thay đổi tổ chức và bạn cũng sẽ tìm thấy một số liên kết hữu ích khác tới nhiều nghiên cứu điển hình hơn về chủ đề này.</p>



<h3 class="wp-block-heading">Tổ chức Cứu trợ và Phát triển Toàn cầu</h3>



<p><a href="https://www.preventionweb.net/organization/global-relief-and-development-mission" target="_blank" rel="noreferrer noopener">Tổ chức Cứu trợ và Phát triển Toàn cầu (GRDO)</a>, được Ludema và các đồng nghiệp giới thiệu trong Sổ tay Nghiên cứu Hành động (2006), là một tổ chức phi chính phủ của Hoa Kỳ và Canada có liên quan đến hơn một trăm tổ chức khác trên toàn thế giới.</p>



<h4 class="wp-block-heading">Bối cảnh</h4>



<p>GRDO đã tiếp cận các tác giả về vấn đề mà họ cho là có vấn đề với hệ thống đánh giá năng lực tổ chức hiện tại đối với các đối tác của mình.</p>



<p>Khi mô tả tình hình cho các chuyên gia tư vấn, họ đề cập đến việc thiếu sự tham gia của các bên liên quan (nội bộ và bên ngoài) với hệ thống;&nbsp;mọi người không ủng hộ nó và họ coi đó là một sự áp đặt tẻ nhạt.</p>



<p>Đã ẩn chứa trong mô tả của họ về hệ thống, là từ vựng dựa trên sự thiếu hụt và những gợi ý đổ lỗi—cả giữa các tổ chức bên liên quan và bản thân GRDO.</p>



<p>Ngoài ra, các tác giả lưu ý rằng GRDO không thể tự coi mình là một đối tác bình đẳng trong những gì vốn được cho là một quá trình xây dựng năng lực và lại không được coi là như vậy.</p>



<h4 class="wp-block-heading">Chủ đề khẳng định</h4>



<p>Như vậy, bước đầu tiên là điều chỉnh lại vấn đề được nhận thức một cách tích cực và xác định một chủ đề khẳng định.&nbsp;Để đạt được mục tiêu (hoặc sự khởi đầu) này, các chuyên gia tư vấn đã đặt ra các câu hỏi nhằm khám phá &#8216;khao khát sâu sắc hơn&#8217; của GRDO.</p>



<p>Theo Johnson và các đồng nghiệp, những câu hỏi quan trọng đầu tiên là:</p>



<blockquote class="wp-block-quote is-layout-flow wp-block-quote-is-layout-flow">
<p><em>“Bạn thực sự muốn gì từ quá trình này?&nbsp;Khi bạn khám phá những hy vọng táo bạo nhất và những khát vọng cao nhất của mình, cuối cùng bạn muốn gì?”</em></p>
</blockquote>



<p>Do đó, bước Xác định đã dẫn đến một số chủ đề;&nbsp;GRDO mong muốn nhiều điều tích cực (Ludema và cộng sự, 2006):</p>



<ul class="wp-block-list">
<li>Học hỏi lẫn nhau về cách xây dựng các tổ chức phi chính phủ năng động, lành mạnh;&nbsp;Và</li>



<li>Khám phá những cách mới để cộng tác bình đẳng với các đối tác của họ.</li>
</ul>



<h4 class="wp-block-heading">Khám phá</h4>



<p>Một nhóm toàn cầu đã được thành lập bao gồm các bên liên quan từ các khu vực khác nhau của GRDO trên khắp thế giới và các khóa tu theo nhóm lớn đã được tổ chức để cả GRDO và các bên liên quan có thể làm quen với AI.</p>



<p>Họ đã đưa ra các phiên bản hơi khác nhau của Giao thức phỏng vấn AI được hiển thị bên dưới.</p>



<p><strong>Giao thức phỏng vấn đánh giá cao</strong></p>



<ul class="wp-block-list">
<li>Hãy nghĩ về khoảng thời gian trong toàn bộ trải nghiệm của bạn với tổ chức khi bạn cảm thấy hào hứng nhất, gắn kết nhất và sống động nhất. Những động lực và yếu tố nào đã khiến nó trở thành một trải nghiệm tuyệt vời? Điều gì ở bạn, những người khác và tổ chức của bạn đã khiến trải nghiệm đó trở thành trải nghiệm tuyệt vời nhất đối với bạn?</li>



<li>Bạn coi trọng điều gì nhất ở bản thân, công việc và tổ chức của mình?</li>



<li>Thực tiễn tốt nhất của tổ chức của bạn là gì (cách bạn quản lý, cách tiếp cận, truyền thống)?</li>



<li>Những khía cạnh độc đáo nào trong văn hóa của bạn có ảnh hưởng tích cực nhất đến tinh thần, sức sống và hiệu quả của tổ chức cũng như công việc của tổ chức?</li>



<li>Yếu tố cốt lõi “mang lại sức sống” cho tổ chức của bạn là gì?</li>



<li>3 hy vọng quan trọng nhất mà bạn có để nâng cao sức khỏe và sức sống của tổ chức trong tương lai là gì?</li>
</ul>



<p><em>Nguồn: Ludema và cộng sự.&nbsp;(2006)</em></p>



<p>Với những câu hỏi tích cực vô điều kiện để định hướng cuộc điều tra, các tổ chức phi chính phủ đối tác khác nhau đã quay trở lại quốc gia nơi họ làm việc để thực hiện &#8216;các chuyến tham quan lắng nghe&#8217; (Ludema và cộng sự, 2006).</p>



<p>Những hoạt động này bao gồm hoạt động điều tra có sự tham gia của các thành viên cộng đồng mà các tổ chức phi chính phủ đang hợp tác, nhằm thu hút càng nhiều tiếng nói càng tốt trong khi khám phá những điểm mạnh cốt lõi tích cực của GRDO và các đối tác của nó.</p>



<p>Hàng nghìn người tham gia đã tham gia vào giai đoạn này, diễn ra trong suốt 1 năm.</p>



<h4 class="wp-block-heading">Mơ</h4>



<p>GRDO và các đối tác NGO của mình đã gặp lại nhau tại các buổi tĩnh tâm nhóm lớn để chia sẻ những điểm mạnh và câu chuyện từ những thắc mắc của họ.&nbsp;Điều này đã giúp họ nói lên tầm nhìn của mình về tương lai tích cực của tổ chức và bắt đầu nảy sinh ý tưởng cho cách tiếp cận chiến lược mới.</p>



<p>Ludema và các đồng nghiệp mô tả giai đoạn này là sự khởi đầu của quá trình thiết kế lại (Ludema et al., 2006: 162):</p>



<blockquote class="wp-block-quote is-layout-flow wp-block-quote-is-layout-flow">
<p>“Một sự bùng nổ ảo của những câu chuyện tích cực đang được chia sẻ và cách GRDO và các đối tác nói về bản thân họ, về nhau cũng như công việc chung của họ đang bắt đầu chuyển từ cuộc trò chuyện về thâm hụt sang cuộc trò chuyện về khả năng.”</p>
</blockquote>



<h4 class="wp-block-heading">Thiết kế</h4>



<p>Phối hợp với các đối tác của mình, GRDO bắt đầu khám phá một cách có hệ thống những cấu trúc xã hội nào có thể hiện thực hóa những tầm nhìn này.&nbsp;Điều này diễn ra trên quy mô toàn cầu, với hàng trăm cuộc họp được tiến hành.</p>



<p>Trong quá trình này, những người tham gia đã tạo ra các cấu trúc đáp ứng theo khu vực—”các đề xuất mang tính khiêu khích”—có thể liên kết các điểm mạnh được phát hiện với những tương lai lý tưởng có thể xảy ra hoặc những gì &#8216;có thể xảy ra&#8217;.</p>



<p>Thông qua sự hợp tác sâu hơn, những hệ thống này đã phát triển thành các hệ thống xây dựng năng lực mới đầy tiềm năng, khác biệt cơ bản với cách tiếp cận trước đây mà GRDO và các đối tác đã sử dụng.</p>



<p>Nhìn rộng ra, đây là những hoạt động mang tính tham gia nhiều hơn và được phân cấp trách nhiệm để các tổ chức phi chính phủ địa phương sẽ tạo ra các giải pháp phù hợp hơn ở các quốc gia khác nhau.</p>



<p>Các tác giả mô tả sự khởi đầu của một sự thay đổi hướng tới tư duy tập trung vào quan hệ đối tác hơn. Họ nhớ lại, sự bình đẳng mong muốn bắt đầu bộc lộ khi từ vựng thay đổi để trở nên giống từ vựng của các đối tác hơn.</p>



<h4 class="wp-block-heading">Định mệnh</h4>



<p>Năm thứ 3 và cũng là năm cuối cùng của hành trình GRDO và các tổ chức phi chính phủ chứng kiến ​​các sáng kiến ​​được chia sẻ và năng lượng ngày càng tăng xung quanh chúng.</p>



<p>Các hoạt động chung đã được triển khai ở các khu vực khác nhau sau đợt tĩnh tâm cuối cùng, chẳng hạn như khởi động các dự án gây quỹ mới ở địa phương và thiết kế lại tổ chức theo một cơ cấu mới, ít phân cấp hơn.</p>



<p>Chi tiết hơn về sáng kiến ​​AI toàn cầu này có thể được tìm thấy trong cuốn sách của Johnson và Ludema (1997), <em>Hợp tác để xây dựng và đo lường năng lực tổ chức: Bài học từ các tổ chức phi chính phủ trên khắp thế giới</em>&nbsp;.</p>



