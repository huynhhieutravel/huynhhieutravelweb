<h3 class="wp-block-heading">SOAR so với SWOT</h3>



<p>Như chúng ta mong đợi từ khung AI, mô hình SOAR bắt đầu bằng việc tìm hiểu.&nbsp;Đây là giai đoạn đầu tiên trong bốn giai đoạn mà người tham gia có thể trải qua với tư cách là một nhóm (Stavros và cộng sự, 2003):</p>



<p><strong>1. Tìm hiểu</strong>: Các câu hỏi tích cực được đặt ra để khám phá những điểm mạnh và nguyện vọng của tổ chức, đồng thời đây là cơ hội tốt để thảo luận cởi mở, tích cực về những hiểu biết chung (hoặc không) về các giá trị và tầm nhìn (Stavros và cộng sự, 2003).</p>



<p>Chúng ta muốn ở đâu?&nbsp;Những điểm mạnh nào đã giúp chúng ta đạt được vị trí hiện tại?&nbsp;Như thế nào và tại sao?</p>



<p><strong>2. Trí tưởng tượng</strong>: Người tham gia nghĩ ra những tương lai tiềm năng.&nbsp;Tầm nhìn, giá trị và sứ mệnh được đồng sáng tạo và việc lặp lại có thể là một phương tiện hữu ích để làm rõ hoặc tái khẳng định định hướng chiến lược của công ty.</p>



<p>Trọng tâm của giai đoạn tưởng tượng là các mục tiêu dài hạn cho một tương lai tốt đẹp hơn là chủ động quản lý rủi ro với các mối đe dọa hoặc điểm yếu trong tâm trí.</p>



<p><strong>3. Đổi mới</strong>: Các mục tiêu chiến lược dài hạn được chia thành các mục tiêu ngắn hạn và phương pháp để đạt được chúng.&nbsp;Đối với một dự án cụ thể, điều này có thể liên quan đến việc phát triển các sản phẩm và khung thời gian;&nbsp;theo nghĩa tổng quát hơn, đó là việc đưa ra các hệ thống để hỗ trợ việc thực hiện.</p>



<p><strong>4. Truyền cảm hứng</strong>: Stavros và các đồng nghiệp giới thiệu&nbsp;Inspire&nbsp;như một giải pháp thay thế cho những gì được coi là hệ thống kiểm soát theo truyền thống (tức là trong trang web văn hóa hoặc trong Quản lý chất lượng toàn diện).</p>



<p>Trong chiến lược thông thường, những điều này có thể đề cập đến KPI và các biện pháp khuyến khích;&nbsp;trong SOAR, truyền cảm hứng bao gồm các hệ thống khuyến khích sự công nhận và khen thưởng đích thực.</p>



<h3 class="wp-block-heading">Áp dụng SOAR</h3>



<p>Tất nhiên, hiểu một framework không giống như đưa nó vào hoạt động.&nbsp;Để đạt được mục tiêu đó, Stavros và Hinrichs (2009) phác thảo một số bước để áp dụng khung SOAR trong&nbsp;<em>Cuốn sách mỏng về bay cao</em>&nbsp;của họ.&nbsp;9 bước của họ như sau:</p>



<ol class="wp-block-list">
<li>Xác định các bên liên quan – Xác định ai sẽ tham gia vào hoạt động này và quyết định cách thức họp.&nbsp;Để phù hợp với mục tiêu hợp tác, toàn diện của AI, những người tham gia phải là các bên liên quan nội bộ đại diện cho các lĩnh vực khác nhau của công ty.</li>



<li>Thiết kế cuộc phỏng vấn AI của bạn – Lên kế hoạch cho các câu hỏi mà bạn định sử dụng;&nbsp;tất nhiên, những điều này sẽ nhằm mục đích phát triển cái nhìn sâu sắc hơn về cốt lõi tích cực của tổ chức.&nbsp;Hiểu được điểm mạnh, thành công và khát vọng của nó là động lực chính, vì vậy câu hỏi của bạn phải phản ánh những mục tiêu này.</li>



<li>Thu hút các bên liên quan – Những hoạt động này sẽ luôn có sự tham gia của các bên liên quan nội bộ và cũng có thể bao gồm các bên liên quan bên ngoài như đối tác, khách hàng hoặc nhà cung cấp nếu thấy phù hợp.&nbsp;Sử dụng câu hỏi của bạn để khám phá những khả năng và tương lai tiềm năng tích cực.</li>



<li>Điều chỉnh lại vấn đề – Các vấn đề sẽ luôn nảy sinh để thảo luận;&nbsp;Cuộc điều tra SOAR tập trung vào sự tập trung tích cực, vì vậy hãy định hình lại các cuộc trò chuyện để xem xét các kết quả mong muốn thay vì tránh né hoặc giảm thiểu các mối đe dọa.</li>



<li>Tóm tắt – Đây là việc làm rõ và khẳng định điểm mạnh của tổ chức – cốt lõi tích cực của tổ chức.</li>



<li>Thiết lập nguyện vọng và xác định kết quả – Đây là một phần quan trọng trong việc xác định hoặc xác định lại tầm nhìn tương lai của tổ chức, điều này lý tưởng sẽ tận dụng những điểm mạnh mà bạn đã xác định chung.&nbsp;Những thứ này sẽ trông như thế nào?&nbsp;Họ sẽ như thế nào?</li>



<li>Đánh giá cơ hội – Nhìn vào những cơ hội đã được tạo ra.&nbsp;Đó là những gì mong muốn nhất?&nbsp;Cái nào mới, sáng tạo và đầy tiềm năng?</li>



<li>Mục tiêu thủ công – Mục tiêu phải xuất phát từ các cơ hội được xác định ở giai đoạn trước.&nbsp;Chúng có thể được liên kết với kết quả để có thể theo dõi và đánh giá tiến độ.&nbsp;Sử dụng các tuyên bố mục tiêu để rõ ràng hơn.</li>



<li>Tạo kế hoạch hành động – Chúng ta sẽ làm việc như thế nào để hướng tới những mục tiêu này?&nbsp;Các kế hoạch hành động cần tạo điều kiện thuận lợi cho việc thực hiện và có thể có kế hoạch cụ thể cho từng mục tiêu.</li>
</ol>



<p>Được triển khai đúng cách với sự tham gia của một nhóm các bên liên quan, khuôn khổ SOAR có mục đích lý tưởng là khuyến khích cam kết tập thể đối với tầm nhìn chung đã xuất hiện (Stavros &amp; Hinrichs, 2009).</p>



