<p>Nhiều người dân trong vùng đã hình thành liên kết với nhau. Nhiều người mở nhà nghỉ, khách sạn để khách du lịch lưu trú. Một số người thì dùng thuyền có sẳn, mua thêm cano để chở khách đi du lịch các đảo xa bờ. Những hải sản đánh bắt mang về cũng được tiêu thụ tốt và giá cả tăng hơn trước.</p>



<p>Dường như đời sống kinh tế của người dân ở đây càng ngày càng phát triển mạnh mẽ và khá giả hơn.</p>



