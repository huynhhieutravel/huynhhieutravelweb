<p>Nam du có từ lâu đời nhưng đến năm 2005 mới được chính thức trở thành một đơn vị hành chính của Việt Nam. Tên gọi của nó có nhiều giả thuyết, nhưng người ta nghiêng về cái tên bắt nguồn từ thời vua Gia Long. Nam Du là từ đọc chạy của nam dự, nghĩa là đảo ở phía nam.</p>



<p>Đảo Nam Du bắt đầu làm du lịch từ năm 2014, đến năm 2015 thì bùng nổ. Đến nay, khi nhắc các tuyến đảo miền Tây thì đây là lựa chọn hàng đầu các bạn trẻ du lịch. Tốc độ tăng trưởng du lịch của nó cũng vô cùng mạnh mẽ.</p>



<p>Năm 2014, chỉ với vài ngàn lượt khách du lịch nhưng tăng trưởng đến 25.000 &#8211; 26.000 lượt khách vào năm 2015. Đến năm 2017 đã có đến 119.000 lượt khách. Từ một hòn đảo hoang vu, Nam Du đã trở thành điểm du lịch thu hút với lượt khách mỗi năm gấp vài chục lần dân số của đảo.</p>



