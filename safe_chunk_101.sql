<h3 class="wp-block-heading">Nhưng cũng có những tiêu cực ở Nam Du khi phát triển du lịch</h3>



<p>Năm 2016, hiện tượng cạn nước bắt đầu xuất hiện ở hòn đảo này. <a href="https://laodong.vn/xa-hoi/xa-dao-nam-du-kien-giang-nhung-ngay-nuoc-quy-hon-tien-528972.bld">Nam Du bị quá tải</a> vì lượt khách gấp vài lần đến hàng chục lần người dân bản xứ ùn ùn kéo đến đây. Các giếng nước bắt đầu khô cạn, nước trở nên hiếm hơn khi đúng dịp mùa khô. Giải pháp được đưa ra là vận chuyển nước từ đất liền vào giải quyết tạm thời nhu cầu, nhưng cũng không phải lâu dài.</p>



<p>Ngoài lượng nước, môi trường ở đây càng bị hủy hoại nghiệm trọng. Từ một hòn đảo hoang sơ, có lẽ Nam Du bắt đầu trở thành một hòn đảo hoang tàn. Rác rưới bị lượng lớn khách du lịch bỏ lại, không phân hủy được. Hòn đảo này lại không thể xử lý rác bằng công nghiệp mà chỉ có thể chôn xuống đất. Hoặc để nó chất cao thành những núi rác đầy mùi hôi.</p>



<p>Đảo Nam Du là hòn đảo xinh đẹp, tuy vậy chúng ta phải nhìn nhận hiện trạng du lịch tràn lan và tác hại nó mang lại. Người dân du lịch cần ý thức nhiều hơn và chính quyền cũng cần có nhiều hoạt động thiết thực để cải tổ môi trường đảo Nam Du.</p>



