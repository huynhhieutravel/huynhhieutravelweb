<h3 class="wp-block-heading">Những thay đổi tích cực mà nó mang lại</h3>



<p>Với những lượt khách du lịch lên đến hàng trăm nghìn, ước tính mỗi năm nó mang lại kinh tế Nam Du và Kiên Giang hàng trăm tỷ đồng. Đời sống người dân bắt đầu được cải thiện dần. Từ việc mưu sinh khó khăn với những chuyến đánh bắt xa bờ, họ đã có cách cải thiện đời sống của mình hơn.</p>



